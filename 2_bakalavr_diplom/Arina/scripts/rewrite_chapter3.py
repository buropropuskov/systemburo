def apply_chapter3_rewrite(doc):
    # границы главы 3
    start = find_heading(doc, STYLE_H1, "3 РЕАЛИЗАЦИЯ ТЕСТИРОВАНИЯ")
    if start < 0:
        start = find_heading(doc, "Heading 1", "3 РЕАЛИЗАЦИЯ")
    if start < 0:
        sys.exit("Не найден заголовок главы 3")
    end = find_heading(doc, STYLE_H1, "ЗАКЛЮЧЕНИЕ", from_idx=start + 1)
    if end < 0:
        end = find_heading(doc, "Heading 1", "ЗАКЛЮЧЕНИЕ", from_idx=start + 1)
    if end < 0:
        sys.exit("Не найден заголовок ЗАКЛЮЧЕНИЕ")

    # удалим всё содержимое главы 3 (оставим сам заголовок H1)
    delete_range(doc, start + 1, end)

    anchor = doc.paragraphs[start]._element

    for kind, payload in CH3_BLOCKS:
        if kind == "T":
            new = make_p(payload, STYLE_TEXT)
            anchor.addnext(new)
            anchor = new
        elif kind == "H2":
            new = make_p(payload, STYLE_H2)
            anchor.addnext(new)
            anchor = new
        elif kind == "H3":
            new = make_p(payload, STYLE_H3)
            anchor.addnext(new)
            anchor = new
        elif kind == "LIST_CAPTION":
            new = make_p(payload, STYLE_LIST)
            anchor.addnext(new)
            anchor = new
        elif kind == "CODE":
            for line in payload.split("\n"):
                new = make_p(line if line else " ", STYLE_CODE)
                anchor.addnext(new)
                anchor = new
        elif kind == "TABLE_CAPTION":
            new = make_p(payload, STYLE_TAB)
            anchor.addnext(new)
            anchor = new
        elif kind == "TABLE":
            headers = payload[0]
            rows = payload[1:]
            tbl = doc.add_table(rows=len(rows) + 1, cols=len(headers))
            tbl.style = "Table Grid"
            for j, h in enumerate(headers):
                tbl.rows[0].cells[j].text = h
            for i, row in enumerate(rows):
                for j, val in enumerate(row):
                    tbl.rows[i + 1].cells[j].text = val
            tbl_el = tbl._element
            tbl_el.getparent().remove(tbl_el)
            anchor.addnext(tbl_el)
            anchor = tbl_el


def main():
    if not SRC.exists():
        sys.exit(f"Не найден {SRC}")
    doc = Document(str(SRC))
    print(f"Открыт {SRC}: {len(doc.paragraphs)} параграфов")
    apply_chapter3_rewrite(doc)
    doc.save(str(OUT))
    print(f"Сохранено: {OUT}")


