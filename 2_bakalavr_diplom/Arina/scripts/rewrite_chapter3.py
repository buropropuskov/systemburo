def make_p(text: str, style_name: str) -> OxmlElement:
    """Создать параграф со стилем из документа (по styleId)."""
    style_id = STYLE_IDS.get(style_name, style_name)
    p = OxmlElement("w:p")
    pPr = OxmlElement("w:pPr")
    pStyle = OxmlElement("w:pStyle")
    pStyle.set(qn("w:val"), style_id)
    pPr.append(pStyle)
    p.append(pPr)
    r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = text
    t.set(qn("xml:space"), "preserve")
    r.append(t)
    p.append(r)
    return p


def find_heading(doc, style_name: str, text_start: str, from_idx: int = 0) -> int:
    """Поиск параграфа с нужным стилем (по имени) и началом текста."""
    target_id = STYLE_IDS.get(style_name, style_name)
    for i in range(from_idx, len(doc.paragraphs)):
        p = doc.paragraphs[i]
        pStyle = p._element.find(qn("w:pPr"))
        if pStyle is not None:
            st = pStyle.find(qn("w:pStyle"))
            if st is not None and (st.get(qn("w:val")) == target_id
                                    or st.get(qn("w:val")) == style_name):
                if p.text.strip().startswith(text_start):
                    return i
    # fallback — по имени стиля python-docx
    for i in range(from_idx, len(doc.paragraphs)):
        p = doc.paragraphs[i]
        if p.style.name == style_name and p.text.strip().startswith(text_start):
            return i
    return -1


def delete_range(doc, start_idx: int, end_idx: int):
    """Удалить параграфы [start_idx, end_idx) по индексам документа."""
    elements = [doc.paragraphs[i]._element for i in range(start_idx, end_idx)]
    for el in elements:
        el.getparent().remove(el)


