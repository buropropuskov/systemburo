def set_run(run, *, size=14, bold=False, italic=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color:
        run.font.color.rgb = color


def add_p(doc, text, *, size=14, bold=False, italic=False,
          align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent_first=True,
          space_before=0, space_after=0, color=None, line=1.5):
    p = doc.add_paragraph()
    p.alignment = align
    if indent_first:
        p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = line
    r = p.add_run(text)
    set_run(r, size=size, bold=bold, italic=italic, color=color)
    return p


def add_heading(doc, text, *, size=16, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT,
                space_before=18, space_after=6, color=None):
    return add_p(doc, text, size=size, bold=bold, align=align,
                 indent_first=False, space_before=space_before,
                 space_after=space_after, color=color, line=1.15)


