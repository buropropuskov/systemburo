import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Меню выпадающего списка не должно быть уже своего содержимого.
 *
 * Кнопку фильтра часто зажимает колонка таблицы, и при жёстком `width: 100%` меню
 * наследовало её ширину вместе с обрезкой: в справочнике организаций из шести пунктов
 * резались пять при ширине меню 117px. Ширина кнопки остаётся нижней границей, а не
 * единственным значением.
 *
 * Проверка на исходнике, а не на отрисовке: jsdom не считает раскладку, и реальную
 * ширину меню там не увидеть - она проверяется замером на стенде.
 */
describe('BaseDropdown — ширина меню', () => {
  const стили = readFileSync(
    resolve(__dirname, '..', 'BaseDropdown.vue'), 'utf8',
  ).split('<style')[1] || '';

  // Базовое правило начинается с начала строки; правило для потока идёт от контейнера.
  const базовое = (стили.match(/^\.base-dropdown__menu\s*\{[^}]*\}/m) || [''])[0];
  const вПотоке = (стили.match(/\.base-dropdown\s+\.base-dropdown__menu\s*\{[^}]*\}/) || [''])[0];

  it('оба правила на месте', () => {
    expect(базовое, 'базовое правило меню').not.toBe('');
    expect(вПотоке, 'правило для меню в потоке').not.toBe('');
  });

  it('в потоке кнопка задаёт нижнюю границу, дальше рост по содержимому', () => {
    expect(базовое, 'width: 100% обрезает пункты по узкой кнопке').not.toMatch(/[\n{]\s*width:\s*100%/);
    expect(вПотоке).toMatch(/min-width:\s*100%/);
    expect(вПотоке).toMatch(/width:\s*max-content/);
  });

  it('нижняя граница задана ТОЛЬКО через контейнер', () => {
    // Телепортнутое меню лежит прямым потомком body, и там 100% - ширина всей
    // страницы: правило без контейнера растянуло меню фильтров Центра на 1600px и
    // вынесло за правый край.
    expect(базовое, 'min-width: 100% в базовом правиле ломает телепортный режим')
      .not.toMatch(/min-width:\s*100%/);
  });

  it('потолок общий - меню не уезжает за край экрана', () => {
    expect(базовое).toMatch(/max-width:\s*min\(/);
  });
});
