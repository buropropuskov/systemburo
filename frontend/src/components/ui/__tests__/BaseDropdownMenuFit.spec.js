import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Меню выпадающего списка не должно быть уже своего содержимого.
 *
 * Кнопку фильтра часто зажимает колонка таблицы, и при жёстком `width: 100%` меню
 * наследовало её ширину вместе с обрезкой: в справочнике организаций из шести пунктов
 * резались пять при ширине меню 117px. Ширина кнопки остаётся нижней границей, а не
 * единственным значением.
 *
 * Проверка на исходнике, а не на отрисовке: jsdom не считает раскладку, и реальную
 * ширину меню там не увидеть - она проверяется замером на стенде.
 */
describe('BaseDropdown — ширина меню', () => {
  const стили = readFileSync(
    resolve(__dirname, '..', 'BaseDropdown.vue'), 'utf8',
  ).split('<style')[1] || '';

  const правило = (стили.match(/\.base-dropdown__menu\s*\{[^}]*\}/) || [''])[0];

  it('правило меню найдено', () => {
    expect(правило).not.toBe('');
  });

  it('ширина кнопки - нижняя граница, а не жёсткое значение', () => {
    expect(правило, 'width: 100% обрезает пункты по узкой кнопке').not.toMatch(/[\n{]\s*width:\s*100%/);
    expect(правило, 'меню не должно быть уже кнопки').toMatch(/min-width:\s*100%/);
    expect(правило, 'и не уже своего содержимого').toMatch(/width:\s*max-content/);
  });

  it('есть потолок, чтобы меню не вылезло за экран', () => {
    expect(правило, 'без max-width длинный пункт растянет меню за границу окна')
      .toMatch(/max-width:\s*min\(/);
  });
});
