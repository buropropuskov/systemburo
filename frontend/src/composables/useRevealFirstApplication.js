import { watch } from 'vue';
import { useOnboardingStore } from '@/stores/onboarding';

/**
 * Значение `reveal.open`, на которое отзывается механика. Дубль строки из
 * `OPEN_TARGETS` (reveal.js) - импорт оттуда потянул бы в страницы списков шину
 * событий и хост тура. От расхождения стережёт спека композабла.
 */
export const REVEAL_FIRST_APPLICATION = 'first-application';

/**
 * Раскрытие карточки заявки по сигналу онбординг-тура (`reveal.open`).
 *
 * Деталь заявки - модалка ВНУТРИ страницы со списком, а не отдельный роут, поэтому
 * driver.js открыть её не может: он умеет подсвечивать и переходить по роутам, но не
 * нажимать на строки. Механику даёт владелец списка - он открывает первую заявку по
 * сигналу и закрывает её, когда сигнал гаснет. Потребителей два: личный кабинет
 * (`UserApplications`, тур заявителя) и Центр заявок (`ApplicationsCenter`, туры
 * согласующего и принимающего), и оба обязаны соблюдать один и тот же контракт.
 *
 * Контракт (три правила, каждое оплачено конкретным сбоем):
 * 1. Пустой список - не открываем ничего. Шаги сегмента карточки помечены
 *    `optional` и в этом случае просто пропускаются.
 * 2. Карточку, открытую человеком, тур не трогает: ни открывает поверх, ни
 *    закрывает за собой.
 * 3. Человек закрыл карточку сам (крестик, Esc, свайп) - тур перестаёт быть её
 *    владельцем. Без этого следующее гашение сигнала закрыло бы карточку, которую
 *    человек к тому моменту открыл заново уже для себя. Отсюда `release()`: его
 *    зовёт метод закрытия самого списка.
 *
 * Обе страницы - Options API, поэтому связывание идёт из `created()`, где уже есть
 * `this` со списком и методами открытия/закрытия. Момент тот же, что у прежней
 * записи в `watch:`, так что сигнал между созданием и монтированием не теряется.
 *
 * @param {object} handlers
 * @param {() => object|undefined} handlers.first первая заявка списка в порядке показа
 * @param {() => boolean} handlers.isOpen открыта ли сейчас карточка
 * @param {(application: object) => void} handlers.open открыть карточку заявки
 * @param {() => void} handlers.close закрыть карточку
 * @returns {{ stop: () => void, release: () => void }}
 */
export function useRevealFirstApplication({ first, isOpen, open, close }) {
  const store = useOnboardingStore();
  let openedByTour = false;
  // Правило 3 в действии: человек закрыл карточку сам, и пока сигнал не сменится,
  // тур её больше не открывает. Без флага повторная попытка (см. ниже) вернула бы
  // карточку на экран при первом же обновлении списка.
  let releasedByUser = false;

  // Следим за сигналом, первой заявкой И состоянием карточки. Список приезжает
  // своим запросом, и на медленной сети сигнал успевает встать раньше данных -
  // приход данных даёт вторую попытку. Состояние карточки нужно по той же
  // причине: «Назад» на шаг «Откройте заявку» гасит сигнал и закрывает карточку,
  // а закрытие идёт с анимацией - следующее «Далее» видело карточку ещё открытой,
  // не открывало её заново, и весь сегмент выбрасывался («на 22 вернуться не могу»).
  const stop = watch(
    () => [store.revealOpen, first(), isOpen()],
    ([target]) => {
      if (target === REVEAL_FIRST_APPLICATION) {
        if (releasedByUser) return;
        const application = first();
        // Правила 1 и 2: открывать нечего либо карточка уже на экране.
        if (!application || isOpen()) return;
        openedByTour = true;
        open(application);
        return;
      }
      // Журнал заявки открывается ИЗ карточки: на этом сигнале карточку держим,
      // иначе шаг про журнал сам же закрывает то, из чего журнал открыт.
      if (target === 'application-history') return;
      // Сигнал сменился на чужой узел или погас. Закрываем только своё: ось `open`
      // общая, по ней же ходят колонка Админки и панель поиска.
      releasedByUser = false;
      if (!openedByTour) return;
      openedByTour = false;
      close();
    },
  );

  return {
    stop,
    /** Правило 3: карточку закрыли помимо тура - владение сброшено. */
    release() {
      openedByTour = false;
      releasedByUser = true;
    },
  };
}
