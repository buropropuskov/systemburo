import { describe, it, expect } from 'vitest';
import { itemsInRange, mergeSelection } from '../rangeSelection';

const строки = [
  { id: 1, имя: 'А' },
  { id: 2, имя: 'Б' },
  { id: 3, имя: 'В', занят: true },
  { id: 4, имя: 'Г' },
  { id: 5, имя: 'Д' },
];
const занят = (i) => i.занят === true;

describe('itemsInRange', () => {
  it('берёт всё между якорем и целью включительно', () => {
    expect(itemsInRange(строки, 2, 4).map((i) => i.id)).toEqual([2, 3, 4]);
  });

  it('работает в обе стороны - выбор снизу вверх тот же', () => {
    expect(itemsInRange(строки, 4, 2).map((i) => i.id)).toEqual([2, 3, 4]);
  });

  it('недоступные строки пропускает, но диапазон ими не обрывает', () => {
    // Уже добавленную в заявку запись выбрать нельзя, однако она не должна и мешать:
    // человек тянет диапазон сквозь неё и ждёт, что края останутся на месте.
    expect(itemsInRange(строки, 2, 4, { isDisabled: занят }).map((i) => i.id)).toEqual([2, 4]);
  });

  it('считает по порядку ОТОБРАЖЕНИЯ, а не по исходному набору', () => {
    // При активном поиске между якорем и целью лежат другие записи.
    const найденные = [строки[4], строки[1], строки[3]];
    expect(itemsInRange(найденные, 5, 4).map((i) => i.id)).toEqual([5, 2, 4]);
  });

  it('якорь вне текущего списка диапазона не даёт', () => {
    // Поиск сузил выдачу, и якорная строка ушла с экрана: гадать, где она была,
    // нельзя - выбор просто не расширяем.
    expect(itemsInRange(строки, 99, 4)).toEqual([]);
    expect(itemsInRange(строки, 2, 99)).toEqual([]);
  });
});

describe('mergeSelection', () => {
  it('добавляет диапазон к снимку без дублей', () => {
    const итог = mergeSelection([строки[0]], [строки[0], строки[1]]);
    expect(итог.map((i) => i.id)).toEqual([1, 2]);
  });

  it('снимок сохраняет порядок и не теряет записей вне диапазона', () => {
    const итог = mergeSelection([строки[4], строки[0]], [строки[1]]);
    expect(итог.map((i) => i.id)).toEqual([5, 1, 2]);
  });
});
