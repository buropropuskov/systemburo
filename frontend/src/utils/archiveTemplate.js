/**
 * Расшифровка шаблонов файлового архива для показа человеку (#1615 followup, S6).
 *
 * Раздел показывал шаблоны так, как их задают в консоли: «{год}/{месяц_2} {МЕСЯЦ}
 * {год}/{дата}/{дата} №{номер}». Это язык того, кто разворачивает систему, а
 * читает раздел дежурный по бюро - ему нужно знать, куда лягут файлы, а не как
 * записан шаблон.
 *
 * Словарь повторяет реестр плейсхолдеров сервера (internal/blankpath/tokens.go).
 * Дублирование осознанное: ради образцов значений заводить отдельную ручку
 * дороже, чем держать здесь список из двух десятков строк. Неизвестный
 * плейсхолдер не прячется и не ломает разбор - остаётся в примере как есть,
 * чтобы новая подстановка на сервере была заметна, а не потерялась.
 */

const TOKENS = {
  'год': { label: 'год', example: '2026' },
  'месяц_число': { label: 'месяц числом', example: '8' },
  'месяц_2': { label: 'месяц двумя цифрами', example: '08' },
  'МЕСЯЦ': { label: 'месяц прописными', example: 'АВГУСТ' },
  'месяц': { label: 'месяц строчными', example: 'август' },
  'день': { label: 'день', example: '3' },
  'день_2': { label: 'день двумя цифрами', example: '03' },
  'дата': { label: 'дата', example: '03.08.2026' },
  'номер': { label: 'номер заявки', example: '20260803-001' },
  'id': { label: 'идентификатор заявки', example: '4821' },
  'заявитель': { label: 'заявитель', example: 'Иванов И.И.' },
  'инициатор': { label: 'инициатор заявки', example: 'Петров П.П.' },
  'статус': { label: 'статус', example: 'Завершено' },
  'согласование': { label: 'состояние согласования', example: 'Согласовано' },
  'организация': { label: 'организация', example: 'Отдел контроля доступа' },
  'компания': { label: 'компания', example: 'Бюро пропусков' },
  'тип': { label: 'наименование вложения', example: 'Автозаявка' },
  'период': { label: 'период действия', example: '01.08.2026 - 05.08.2026' },
  'вложение_id': { label: 'идентификатор вложения', example: '9134' },
};

const TOKEN_RE = /\{([^{}]+)\}/g;

/**
 * Пример того, что получится по шаблону: плейсхолдеры заменяются образцами
 * значений, литералы и разделители сохраняются.
 * @param {string} template шаблон каталогов или имени файла
 * @returns {string}
 */
export function renderTemplateExample(template) {
  return String(template || '').replace(TOKEN_RE, (whole, key) => {
    const token = TOKENS[key];
    return token ? token.example : whole;
  });
}
