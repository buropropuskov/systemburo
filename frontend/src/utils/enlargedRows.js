/**
 * Режим укрупнённых строк таблиц прохода: запоминается на устройстве, отдельно на
 * каждый пост.
 *
 * Обе таблицы (люди и машины) держали свою копию чтения и записи с одинаковым
 * глотанием ошибок. Хранилище недоступно в приватном окне и при запрете сайту
 * данных, поэтому обращение обёрнуто: настройка вида не тот случай, ради которого
 * стоит ронять таблицу.
 */

/**
 * @param {string} key ключ хранилища
 * @returns {boolean} включён ли режим (по умолчанию нет)
 */
export function readEnlarged(key) {
  try {
    return localStorage.getItem(key) === '1';
  } catch {
    return false;
  }
}

/**
 * @param {string} key ключ хранилища
 * @param {boolean} value новое состояние
 */
export function writeEnlarged(key, value) {
  try {
    localStorage.setItem(key, value ? '1' : '0');
  } catch {
    // Хранилище недоступно - режим просто не переживёт перезагрузку.
  }
}
