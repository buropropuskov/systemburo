/**
 * Маршруты, на которых оболочка приложения (шапка, навигация, блокирующие
 * оверлеи входа) не показывается.
 *
 * Список общий у нескольких потребителей и обязан оставаться одним: `showChrome`
 * прячет здесь шапку и меню, гейт согласия (#1567) - своё окно. Разъехавшись,
 * они дают экран, где окно согласия висит поверх формы логина или страницы
 * технических работ, то есть поверх того, чем пользователь ещё не управляет.
 *
 * `/` - страница входа: `LoginComponent` держит 1.5с анимации успеха между
 * `setTokens` и `push('/news')`, и в это окно `isAuthenticated` уже true, а
 * маршрут ещё `/`.
 */
export const SHELL_HIDDEN_PATHS = ['/', '/500', '/maintenance'];

/**
 * Лежит ли маршрут вне оболочки приложения.
 * @param {string} path
 * @returns {boolean}
 */
export function isShellHiddenPath(path) {
  return SHELL_HIDDEN_PATHS.includes(path);
}
