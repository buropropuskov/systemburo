package fakedata

import "fmt"

// Годовая часть серии паспорта у вымышленных документов. Вторая пара цифр серии --
// год выпуска бланка: у паспорта образца 1997 года это 97 и далее по возрастанию, а
// бланков будущих лет ещё не существует. Поэтому серия с годом из этого диапазона
// сегодня не может принадлежать настоящему паспорту, тогда как код региона в первой
// паре остаётся правдоподобным.
//
// Признак стареет: к 2030 году нижнюю границу придётся поднять. Первым это заметит
// TestPassport_SeriesYearPartIsUnissued -- он сверяет год с календарём, а не с этими
// константами, поэтому покраснеет сам, без напоминания.
//
// Прежнее обоснование через «коды 95-99 не существуют» было неверным: 95 -- Чеченская
// Республика, 97 и 99 -- дополнительные коды Москвы, серии с ними выдаются.
const (
	passportYearFrom = 30
	passportYearTo   = 94
)

// PassportRegionCodes -- коды регионов для первой пары цифр серии. Список неполный и
// таким задуман: нужен правдоподобный вид, а не справочник подразделений.
var PassportRegionCodes = []int{1, 3, 4, 5, 8, 11, 12, 18, 22, 24, 27, 32, 36, 40, 45, 50, 52, 54, 60, 63, 66, 69, 71, 74, 77, 78, 86, 92, 95}

// Passport собирает строку "серия номер" в виде, в котором её вводят на фронте: поле
// employee.passport_series_number -- свободный текст без маски (см. EmployeeForm.vue,
// на бэке проверяется только непустота), поэтому формат подобран для читаемости.
func Passport(s *Stream) string {
	region := Pick(s, PassportRegionCodes)
	year := IntRange(s, passportYearFrom, passportYearTo)
	number := IntRange(s, 0, 999999)
	return fmt.Sprintf("%02d%02d %06d", region, year, number)
}

// Patent собирает номер патента на работу -- документа, который указывают иностранные
// граждане в анкете сотрудника (employee.patent_number, тоже свободный текст).
//
// В отличие от паспорта, проверяемого признака «такой номер не выдавался» здесь нет:
// однозначно описанной структуры номера патента в открытом доступе не найти. Номер
// просто вымышленный, на стенде он ни с чем не сверяется и никуда не передаётся.
func Patent(s *Stream) string {
	region := Pick(s, PassportRegionCodes)
	year := IntRange(s, passportYearFrom, passportYearTo)
	number := IntRange(s, 0, 9999999)
	return fmt.Sprintf("%02d %02d %07d", region, year, number)
}

// PhoneOperatorCode -- код "оператора" для вымышленных телефонов стенда. У
// российской нумерации нет официального тестового диапазона наподобие 555 у
// североамериканских операторов, и гарантии, что 999 никогда не будет выделен
// реальному оператору, тоже нет. Это практическое соглашение, а не резерв
// регулятора: данные стенда никуда не рассылаются и не сверяются с внешними
// системами, а по формату номер остаётся валидным российским (фронт проверяет
// только код страны 7/8 и первую цифру кода оператора в диапазоне 3-9, см.
// isValidRussianPhone в useRussianPhoneMask.js).
const PhoneOperatorCode = "999"

// Phone возвращает номер в виде, в котором его хранит бэкенд: "+7" и десять
// цифр без разделителей (см. contact_phone в api_contract_test.go). Маску для
// показа накладывает фронт.
func Phone(s *Stream) string {
	subscriber := IntRange(s, 0, 9999999)
	return fmt.Sprintf("+7%s%07d", PhoneOperatorCode, subscriber)
}
