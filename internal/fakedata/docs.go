package fakedata

import "fmt"

// PassportReservedPrefixes -- значения старших двух цифр серии паспорта, которых
// не существует ни у одного субъекта РФ. Серия паспорта нового образца кодирует
// код территориального подразделения, выдавшего документ, а таких подразделений
// на всю страну меньше девяноста пяти -- даже с учётом регионов, вошедших в состав
// РФ в 2014 и 2022 годах. Значения 95-99 гарантированно ничего не кодируют, и
// вымышленный документ с такой серией поэтому не может совпасть с серией
// настоящего паспорта, какие бы цифры ни стояли дальше.
var PassportReservedPrefixes = []int{95, 96, 97, 98, 99}

// Passport собирает строку "серия номер" в виде, в котором её вводят на фронте:
// поле employee.passport_series_number -- свободный текст без маски (см.
// EmployeeForm.vue), поэтому формат подобран для читаемости, а не под парсер.
func Passport(s *Stream) string {
	prefix := Pick(s, PassportReservedPrefixes)
	yearPart := IntRange(s, 0, 99)
	number := IntRange(s, 0, 999999)
	return fmt.Sprintf("%02d%02d %06d", prefix, yearPart, number)
}

// Patent собирает номер патента на работу -- документа, который указывают
// иностранные граждане в анкете сотрудника (employee.patent_number, тоже
// свободный текст). Серия использует тот же резерв, что и Passport: патент такой
// же официальный документ, и совпадение с настоящим номером здесь так же
// нежелательно, как у паспорта.
func Patent(s *Stream) string {
	prefix := Pick(s, PassportReservedPrefixes)
	region := IntRange(s, 0, 99)
	number := IntRange(s, 0, 9999999)
	return fmt.Sprintf("%02d %02d %07d", prefix, region, number)
}

// PhoneOperatorCode -- код "оператора" для вымышленных телефонов стенда. У
// российской нумерации нет официального тестового диапазона наподобие 555 у
// североамериканских операторов, и гарантии, что 999 никогда не будет выделен
// реальному оператору, тоже нет. Это практическое соглашение, а не резерв
// регулятора: данные стенда никуда не рассылаются и не сверяются с внешними
// системами, а по формату номер остаётся валидным российским (фронт проверяет
// только код страны 7/8 и первую цифру кода оператора в диапазоне 3-9, см.
// isValidRussianPhone в useRussianPhoneMask.js).
const PhoneOperatorCode = "999"

// Phone возвращает номер в виде, в котором его хранит бэкенд: "+7" и десять
// цифр без разделителей (см. contact_phone в api_contract_test.go). Маску для
// показа накладывает фронт.
func Phone(s *Stream) string {
	subscriber := IntRange(s, 0, 9999999)
	return fmt.Sprintf("+7%s%07d", PhoneOperatorCode, subscriber)
}
