package fakedata

import (
	"context"
	"fmt"
	"log/slog"

	"systemburo/internal/models"

	"gorm.io/gorm"
)

// Step -- один вид наполнения: справочники, пользователи, заявки, проходы. Шаги
// перечислены в Steps в порядке зависимостей и выполняются последовательно.
//
// Последовательно не из осторожности: номер заявки считается как число заявок за сутки
// плюс один, внутри транзакции и без блокировки, а уникального индекса на номере нет.
// Параллельные шаги выдали бы заявкам одинаковые номера, и дубль прошёл бы молча.
type Step interface {
	// Name -- имя шага для вывода и сообщений об ошибках.
	Name() string
	// Plan -- что шаг создаст при таком профиле. Вызывается без записи в базу.
	Plan(p Profile) []PlanItem
	// Run наливает данные и регистрирует созданное в партии.
	Run(ctx context.Context, env *Env) error
}

// PlanItem -- строка предварительного показа: что и сколько создастся.
type PlanItem struct {
	// Entity -- вид сущности из констант models.AuditEntity*.
	Entity string
	// Title -- название вида для человека, в именительном падеже множественного числа.
	Title string
	Count int
	// Mark -- строка описывает не новые записи, а отметки на уже существующих
	// (въезд/выезд через пост). Такие строки идут в предварительном показе отдельно и
	// не входят в «всего создастся»: удалять по ним нечего, а число здесь -- оценка, не
	// потолок (сколько машин и сотрудников партии дойдёт до поста, известно только после
	// розыгрыша стадий обработки, а Plan по контракту базу не читает).
	Mark bool
}

// Env -- окружение шага: куда писать и что регистрировать.
type Env struct {
	DB      *gorm.DB
	Batch   *Batch
	Profile Profile
	// Seed -- источник случайности партии. Шаги берут из него свои генераторы, чтобы
	// повтор с тем же значением давал ту же партию.
	Seed int64
	// UserPassword -- пароль создаваемых пользователей, печатается в итоговой сводке.
	// Пустая строка -- usersStep берёт DefaultUserPassword.
	UserPassword string
	// PasswordPolicy -- политика паролей стенда, которой должен соответствовать
	// UserPassword. Нулевое значение (MinLength<=0) означает "не передана" --
	// usersStep берёт models.DefaultPasswordPolicy(). Читается вызывающим кодом
	// заранее (settingsService.GetPasswordPolicy в cmd/server/fake.go): fakedata не
	// тянет зависимость на internal/config и на процесс чтения системных настроек
	// конкретного окружения запуска, ей отдают уже готовое значение.
	PasswordPolicy models.PasswordPolicy
	// Consent -- действующая редакция согласия на обработку персональных данных, за
	// которую расписываются создаваемые работники. Читается вызывающим кодом заранее
	// (см. PasswordPolicy рядом -- та же причина). Нулевое значение означает
	// «настройки не прочитаны»: согласие всё равно выдаётся, но первой редакцией.
	Consent ConsentStamp
	// ActorUserID -- от чьего имени пишутся записи истории. Заполняется resolveActor
	// перед прогоном шагов; ноль означает, что подходящей учётной записи не нашлось.
	ActorUserID int
}

// ConsentStamp -- редакция и отпечаток текста согласия на обработку ПД (#1567), с
// которыми записывается согласие созданного работника.
//
// Обе величины обязаны совпадать с настройками стенда: гейт сравнивает принятую
// редакцию с требуемой, и согласие, записанное «просто первой» редакцией, не откроет
// работнику вход, если администратор уже поднимал текст.
type ConsentStamp struct {
	Version int
	Hash    string
}

// resolveActor выбирает, от чьего имени наливка пишет историю: супер-администратор
// стенда, а если его нет -- любой администратор.
//
// Ноль в actor_user_id -- это ссылка на несуществующего пользователя, а не «автор
// неизвестен»: колонка хранится без внешнего ключа, поэтому запись пройдёт, но в
// истории появится актор, которого нет. Цель наливки в том, чтобы данные не отличались
// от заведённых руками, а на живом стенде справочники заводит именно администратор.
//
// Пустой результат возможен только там, где учётные записи ещё не заведены (тесты до
// сида): падать из-за истории не стоит, поэтому остаётся ноль.
func resolveActor(ctx context.Context, db *gorm.DB) int {
	lookup := func(query string) int {
		var id int
		if err := db.WithContext(ctx).Raw(query).Scan(&id).Error; err != nil {
			// Пустой результат ошибкой не считается, поэтому сюда попадает только
			// настоящий сбой запроса. Он всё равно уронит первый же шаг наливки, но
			// молча превратиться в «автора не нашли» не должен.
			slog.Error("наливка: не удалось определить автора истории", "error", err)
			return 0
		}
		return id
	}
	id := lookup(`SELECT id FROM users WHERE is_super_admin = true AND is_active = true ORDER BY id LIMIT 1`)
	if id == 0 {
		id = lookup(`SELECT id FROM users WHERE is_admin = true AND is_active = true ORDER BY id LIMIT 1`)
	}
	return id
}

// Steps перечисляет шаги наполнения в порядке зависимостей: справочники раньше
// пользователей, пользователи раньше заявок, заявки раньше проходов.
//
// Организации и компании -- первыми: все остальные шаги (#1682) заводят сущности,
// которым организации уже нужны как внешний ключ. Пользователи (usersStep) идут сразу
// за ними: им нужны только организации и компании, а не гражданства/марки/форматы
// реестров или сами реестры -- держать шаг рядом с его единственной зависимостью
// точнее, чем ставить его в конец списка без причины, и как честный побочный эффект
// даёт раннюю, недвусмысленную ошибку на профиле без организаций (до того, как до
// той же проверки дойдёт registriesStep). Справочники-без-профиля (места разгрузки/
// марки/гражданства/форматы номеров) и таблицы постов не зависят друг от друга и от
// организаций, порядок между ними и usersStep значения не имеет. Реестры сотрудников
// и машин (registriesStep) идут следующими: они ссылаются на организации/компании/
// гражданства/марки/форматы, которые должны существовать в базе к моменту их
// наливки. Чёрные списки (blacklistsStep) идут следующими: похожие пары строятся от
// реальных записей реестров, а значит реестры должны быть уже наполнены. Заявки
// (applicationsStep) идут следующими: подаются от пользователей usersStep, вложениями
// несут людей/машины из реестров registriesStep и обязаны не задеть активные записи
// чёрного списка blacklistsStep (иначе гард ЧС в SubmitCompleteApplication отклонит
// заявку) -- каждая из этих зависимостей уже должна быть в базе. Стадии обработки
// (stagesStep) идут следующими: разыгрывают переходы по уже поданным заявкам
// applicationsStep руками принимающих usersStep и согласующих, назначенных при подаче --
// и заявки, и все эти люди обязаны существовать в базе раньше. Проходы (passagesStep)
// идут последними: отмечают въезд/выезд машин и сотрудников через посты у заявок,
// принятых в работу stagesStep -- без принятия в работу их не видно ни в одной
// таблице поста, отмечать нечего.
func Steps() []Step {
	return []Step{
		organizationsStep{},
		usersStep{},
		lookupsStep{},
		postsStep{},
		registriesStep{},
		blacklistsStep{},
		applicationsStep{},
		stagesStep{},
		passagesStep{},
	}
}

// Plan собирает предварительный показ по всем шагам.
func Plan(p Profile) []PlanItem {
	var items []PlanItem
	for _, step := range Steps() {
		items = append(items, step.Plan(p)...)
	}
	return items
}

// PlanTotal -- сколько записей создастся всего. Строки отметок (PlanItem.Mark) сюда не
// входят: они ничего не создают.
func PlanTotal(items []PlanItem) int {
	total := 0
	for _, item := range items {
		if item.Mark {
			continue
		}
		total += item.Count
	}
	return total
}

// PlanRecords и PlanMarks делят предварительный показ на то, что создастся, и то, что
// будет отмечено. Порядок строк внутри каждой части сохраняется.
func PlanRecords(items []PlanItem) []PlanItem { return filterPlan(items, false) }

// PlanMarks -- строки об отметках на уже существующих записях.
func PlanMarks(items []PlanItem) []PlanItem { return filterPlan(items, true) }

func filterPlan(items []PlanItem, mark bool) []PlanItem {
	out := make([]PlanItem, 0, len(items))
	for _, item := range items {
		if item.Mark == mark {
			out = append(out, item)
		}
	}
	return out
}

// Run прогоняет шаги наполнения и закрывает партию сводкой.
func Run(ctx context.Context, env *Env) error {
	if env.ActorUserID == 0 {
		env.ActorUserID = resolveActor(ctx, env.DB)
	}
	for _, step := range Steps() {
		if err := step.Run(ctx, env); err != nil {
			// Партия остаётся с уже зарегистрированными записями и не откатывается:
			// иначе созданное до сбоя останется на стенде без перечня, по которому его
			// потом удалять.
			return fmt.Errorf("шаг %q: %w", step.Name(), err)
		}
	}
	if err := env.Batch.Close(ctx); err != nil {
		return err
	}
	return nil
}
