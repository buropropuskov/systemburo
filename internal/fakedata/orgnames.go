package fakedata

import "fmt"

// OrgLegalForms -- организационно-правовые формы для конструктора названий. ИП в
// список не входит: у индивидуального предпринимателя в реквизитах стоит ФИО
// человека ("ИП Иванов И.И."), а не название вида "Севертранс" -- сочетание
// "ИП Севертранс" выглядело бы неправдоподобно. Полный перечень форм, которые
// вообще распознаёт система, шире (см. internal/normalize/orgname.go).
var OrgLegalForms = []string{"ООО", "АО", "ЗАО", "ОАО", "ПАО"}

// orgNameRoots и orgNameSuffixes -- конструктор наименований: корень и суффикс
// склеиваются без пробела ("Север" + "транс" = "Севертранс"). Раздельные списки
// вместо готовых названий дают len(roots)*len(suffixes) сочетаний из небольшого
// словаря -- для профиля "large" (50 организаций и 50 компаний, каждые на своём
// потоке) этого с большим запасом хватает без повтора. Слова в двух списках не
// пересекаются: иначе комбинация "корень == суффикс" склеивала бы название само с
// собой ("Промпром").
var orgNameRoots = []string{
	"Север", "Юг", "Восток", "Запад", "Регион", "Центр", "Прайм", "Гранд",
	"Альфа", "Юнион", "Стандарт", "Метрополь", "Магистраль", "Кама", "Волга",
	"Урал", "Сибирь", "Пром", "Балтика", "Оптима",
}

var orgNameSuffixes = []string{
	"транс", "логистика", "карго", "снаб", "торг", "строй", "сервис", "ресурс",
	"дистрибьюшн", "холдинг", "групп", "трейд", "комплект", "поставка",
	"экспресс", "авто",
}

// orgNameMaxAttempts -- сколько раз OrgNameGenerator пробует подобрать свободную
// комбинацию корня и суффикса, прежде чем сдаться. len(orgNameRoots) *
// len(orgNameSuffixes) = 320 сочетаний на один поток (одну сущность -- организации
// и компании генерируются на разных потоках), профиль "large" просит не больше 50
// сущностей каждого вида, так что отказ в пределах лимита означает испорченный
// вызов (переопределение -orgs/-companies далеко за пределы профиля), а не
// исчерпание словаря в штатном режиме.
const orgNameMaxAttempts = 2000

// OrgNameGenerator -- генератор наименований организаций/компаний с памятью
// выданных: имя не должно повторяться в пределах партии, поэтому генератор, а не
// чистая функция.
type OrgNameGenerator struct {
	stream *Stream
	used   map[string]bool
}

// NewOrgNameGenerator заводит генератор на отдельном потоке domain. Организации и
// компании -- разные сущности с разными таблицами, поэтому вызывающий код заводит
// два генератора с разными domain ("orgnames", "companynames"), и их
// последовательности не пересекаются.
func NewOrgNameGenerator(seed int64, domain string) *OrgNameGenerator {
	return &OrgNameGenerator{stream: NewStream(seed, domain), used: make(map[string]bool)}
}

// Next выдаёт название вида "ООО Севертранс", ранее в этой партии не выданное.
func (g *OrgNameGenerator) Next() (string, error) {
	for attempt := 0; attempt < orgNameMaxAttempts; attempt++ {
		root := Pick(g.stream, orgNameRoots)
		suffix := Pick(g.stream, orgNameSuffixes)
		core := root + suffix
		if g.used[core] {
			continue
		}
		g.used[core] = true
		form := Pick(g.stream, OrgLegalForms)
		return fmt.Sprintf("%s %s", form, core), nil
	}
	return "", fmt.Errorf("не удалось подобрать свободное название за %d попыток: словарь партии исчерпан", orgNameMaxAttempts)
}
