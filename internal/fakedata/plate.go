// plateMaxAttempts -- сколько раз PlateGenerator пробует подобрать свободную
// комбинацию, прежде чем сдаться. Пространство номеров одного региона -- 12 * 999
// * 144 ~ 1.7 млн, а профиль "large" просит не больше 2000 машин, так что отказ
// в пределах этого лимита означает не "не повезло", а испорченный вызов (например,
// -cars, переопределённый на порядок больше профиля).
const plateMaxAttempts = 5000

// PlateGenerator -- генератор госномеров с памятью выданных: номер не должен
// повторяться в пределах партии, поэтому генератор, а не чистая функция.
type PlateGenerator struct {
	stream *Stream
	used   map[string]bool
}

// NewPlateGenerator заводит генератор номеров на отдельном потоке "plates",
// независимом от остальных доменов партии.
func NewPlateGenerator(seed int64) *PlateGenerator {
	return NewPlateGeneratorWithDomain(seed, "plates")
}

// NewPlateGeneratorWithDomain -- как NewPlateGenerator, но на своём домене потока. Нужен,
// когда в одной партии требуется несколько независимых наборов номеров: например, номера
// реестра машин (домен "plates", registries.go) и номера независимых записей чёрного
// списка (#1682, том 4) должны идти разными потоками, иначе оба генератора с одним и тем
// же -seed повторили бы одну и ту же последовательность номеров.
func NewPlateGeneratorWithDomain(seed int64, domain string) *PlateGenerator {
	return &PlateGenerator{stream: NewStream(seed, domain), used: make(map[string]bool)}
}

// Next выдаёт номер вида "А123ВС77", ранее в этой партии не выданный.
func (g *PlateGenerator) Next() (string, error) {
	for attempt := 0; attempt < plateMaxAttempts; attempt++ {
		plate := g.candidate()
		if !g.used[plate] {
			g.used[plate] = true
			return plate, nil
		}
	}
	return "", fmt.Errorf("не удалось подобрать свободный номер за %d попыток: пространство номеров партии исчерпано", plateMaxAttempts)
}

func (g *PlateGenerator) candidate() string {
	letter1 := Pick(g.stream, plateLetterRunes)
	// Серийный номер начинается с 1: "000" на настоящих знаках не выдаётся, и
	// вымышленный номер с нулевой серией сразу выглядел бы сгенерированным.
	number := IntRange(g.stream, 1, 999)
	letter2 := Pick(g.stream, plateLetterRunes)
	letter3 := Pick(g.stream, plateLetterRunes)
	region := Pick(g.stream, PlateRegionCodes)
	return fmt.Sprintf("%c%03d%c%c%s", letter1, number, letter2, letter3, region)
}
