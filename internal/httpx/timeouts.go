// Package httpx - таймауты HTTP-сервера и снятие срока записи для тех обработчиков,
// которым он мешает по существу.
//
// Общий таймаут записи и потоковые ответы противоречат друг другу: net/http ставит
// срок один раз на весь ответ, от разбора заголовков до последнего байта, и не знает,
// что SSE-поток живёт десять минут по замыслу, а ZIP файлового архива собирается на
// лету. Значение, при котором оба выживают, - это час, то есть отсутствие таймаута
// для всех остальных методов. Поэтому предел ставится общий и умеренный, а редкие
// длинные обработчики снимают его с себя явно.
package httpx

import (
	"fmt"
	"net/http"
	"time"

	"github.com/labstack/echo/v4"
)

// ServerTimeouts - сроки жизни HTTP-соединения. Нулевое поле означает "без
// ограничения": это семантика самого net/http, и менять её здесь нельзя - иначе
// выключить таймаут параметром окружения стало бы невозможно.
type ServerTimeouts struct {
	// ReadHeader - на приём заголовков запроса. Единственная защита от slowloris:
	// без неё соединение, отправляющее заголовок по байту в минуту, держит горутину
	// сколько угодно долго и стоит атакующему одного сокета.
	ReadHeader time.Duration
	// Read - на приём запроса целиком, вместе с телом.
	Read time.Duration
	// Write - на формирование и отправку ответа. Отсчёт идёт от конца чтения
	// заголовков, поэтому в него попадает и работа обработчика, а не только запись
	// в сеть: медленный запрос обрывается этим сроком так же, как медленный клиент.
	Write time.Duration
	// Idle - сколько keep-alive соединение ждёт следующего запроса.
	Idle time.Duration
}

// ApplyServerTimeouts проставляет сроки серверу Echo (e.Server) до его запуска.
func ApplyServerTimeouts(srv *http.Server, t ServerTimeouts) {
	srv.ReadHeaderTimeout = t.ReadHeader
	srv.ReadTimeout = t.Read
	srv.WriteTimeout = t.Write
	srv.IdleTimeout = t.Idle
}

// AllowLongResponse снимает срок записи с текущего соединения - для обработчиков,
// у которых долгий ответ и есть работа: SSE-поток (10 минут по замыслу) и потоковые
// выгрузки файлового архива (nginx отводит им час, и обрыв на середине оставил бы
// битый архив). Вызывать до первого записанного байта.
//
// Снимается срок ровно этого соединения, на остальные запросы он продолжает
// действовать. Ошибку возвращает, а не глушит: если снять срок не удалось, длинный
// ответ оборвётся посреди потока по HTTP_WRITE_TIMEOUT, и выглядеть это будет как
// испорченный файл, а не как отказ, - такое обязано попасть в лог.
func AllowLongResponse(c echo.Context) error {
	if err := http.NewResponseController(c.Response()).SetWriteDeadline(time.Time{}); err != nil {
		return fmt.Errorf("clear write deadline: %w", err)
	}
	return nil
}
