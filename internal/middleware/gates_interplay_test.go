package middleware_test

import (
	"sort"
	"testing"

	mw "systemburo/internal/middleware"

	"github.com/stretchr/testify/assert"
)

// Гейт согласия и гейт обязательной смены пароля стоят один за другим, и оба
// отвечают 403 на всё, кроме своего белого списка. Порядок для человека такой:
// сначала согласие, потом свой пароль. Значит, пока на экране окно согласия,
// парольный гейт обязан пропускать всё, чем это окно живёт.
//
// Иначе получается запертая дверь с двух сторон: смену пароля закрывает гейт
// согласия, принятие согласия закрывает парольный гейт, и работник с паролем из
// письма не попадает в систему вообще. Так и было после того, как заведение
// учётной записи стало поднимать признак смены всем подряд: на установке с
// включённым согласием запирался каждый новый работник. Ни один из двух
// гвард-тестов этого не ловил - каждый сверял свой список с роутером, а не списки
// между собой.
func TestGates_ConsentWhitelistIsSubsetOfPasswordWhitelist(t *testing.T) {
	// Билет real-time потока - осознанное исключение: смена пароля отзывает все
	// сессии, человек входит заново, и поток поднимается с нуля. Причина
	// расписана у самих списков.
	allowedMisses := map[string]bool{
		"POST /api/events/ticket": true,
	}

	missing := make([]string, 0)
	for key := range mw.PDConsentWhitelist {
		if allowedMisses[key] || mw.MustChangePasswordWhitelist[key] {
			continue
		}
		missing = append(missing, key)
	}
	sort.Strings(missing)

	assert.Empty(t, missing,
		"эти роуты пропускает гейт согласия, но закрывает парольный: окно согласия упрётся в требование сменить пароль, а сменить его не даст гейт согласия")
}
