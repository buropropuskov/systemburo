package models

import "time"

// Журнал уничтожения персональных данных (#2357).
//
// Удаление данных из работающей системы не удаляет их из снятых ранее резервных
// копий: восстановление возвращает всё как было, вместе с записями, которые оператор
// обязан был уничтожить. Закон допускает держать копии ограниченный срок при условии,
// что после восстановления удаления применяются заново, - а выполнять это условие
// нечем, пока система не ведёт перечня уничтоженного.
//
// Почему отдельная таблица, а не audit_log, куда в этом проекте идут все истории:
//
//   - перечень обязан пережить сами копии, а audit_log чистится уборкой по сроку
//     (группа audit). Свидетельство ушло бы раньше копии, из которой данные
//     возвращаются, - то есть ровно тогда, когда оно и нужно;
//   - у заявки, уничтоженной целиком, вместе с ней уходит и её история в audit_log
//     (PurgeApplication удаляет её намеренно: в пояснениях записей стоят ФИО).
//     Хранить свидетельство там же, откуда его выносит сама операция, нельзя;
//   - отметка о повторном применении правится по месту, а запись audit_log по
//     смыслу неизменяема.
//
// Персональных данных в записи нет и быть не должно: при восстановлении цель
// опознаётся идентификатором, номером заявки и отпечатками документов - ни ФИО, ни
// паспорта, ни телефона. Требование закрыто тестом
// TestDestructionLog_KeepsNoPersonalData.
type DestructionRecord struct {
	ID int `json:"id"`

	// EntityType - что уничтожено: application, organization либо unique_employee
	// (человек как субъект персональных данных).
	EntityType string `gorm:"size:50;not null;index" json:"entity_type"`
	// EntityID - идентификатор цели. У человека своего идентификатора нет: он
	// опознаётся отпечатками документов ниже.
	EntityID *int `gorm:"index" json:"entity_id,omitempty"`
	// Action - обезличено (DestructionAnonymized) или уничтожено целиком
	// (DestructionPurged).
	Action string `gorm:"size:30;not null;index" json:"action"`
	// Basis - основание уничтожения: истёк срок хранения, решение оператора,
	// требование субъекта. Без основания запись бессмысленна как свидетельство,
	// поэтому оно обязательно.
	Basis string `gorm:"size:50;not null" json:"basis"`

	// ApplicationNumber - номер заявки. Персональными данными он не является, а при
	// разборе именно по нему запись и опознают: голый идентификатор человеку,
	// читающему акт, не говорит ничего.
	ApplicationNumber string `gorm:"size:100" json:"application_number,omitempty"`
	// SubjectAnchors - строки, которые были обезличены у человека, в виде
	// «таблица:идентификатор» через запятую. По ним его находят заново после
	// восстановления из копии.
	//
	// Здесь намеренно НЕ лежит ни документ, ни его свёртка, ни отпечаток свёртки.
	// Серия и номер паспорта - это десять цифр: отпечаток от них перебирается за
	// минуты, а журнал переживает и сами данные, и резервные копии, то есть стал бы
	// последним местом, где уничтоженный паспорт восстановим. Ключ поиска берётся не
	// отсюда, а из самой вернувшейся строки: она приезжает из копии вместе со своей
	// свёрткой (см. replaySubjectAnonymize). Храним, ГДЕ взять ключ, а не какой он.
	SubjectAnchors string `gorm:"type:text" json:"-"`

	// Rows и Files - объём уничтоженного: строк в базе и файлов на диске. Нужны
	// акту: без них документ подтверждает факт, но не объём.
	Rows  int `gorm:"not null;default:0" json:"rows"`
	Files int `gorm:"not null;default:0" json:"files"`

	// ActorID - учётная запись, если операция шла через интерфейс. У консольной
	// команды её нет: доступ к консоли сервера не равен учётной записи в системе.
	ActorID *int `gorm:"index" json:"actor_id,omitempty"`
	// ActorNote - по чьему решению, словами. Заполняется всегда: запись переживает
	// и учётную запись, и саму систему, а «по чьему решению» - обязательная графа
	// акта.
	ActorNote string `gorm:"size:200;not null" json:"actor_note"`

	CreatedAt time.Time `gorm:"index" json:"created_at"`

	// Replays и ReplayedAt - сколько раз уничтожение применялось заново после
	// восстановления из копии и когда в последний раз. Запись при этом не
	// удаляется: следующая копия может оказаться ещё старше этой.
	Replays    int        `gorm:"not null;default:0" json:"replays"`
	ReplayedAt *time.Time `json:"replayed_at,omitempty"`
}

func (DestructionRecord) TableName() string { return "destruction_log" }
