package models

import "time"

// Журнал выдач сведений о человеке третьим лицам (#2356).
//
// Передача сведений по запросу государственного органа - это раскрытие персональных
// данных третьему лицу. При проверке оператор обязан показать, что раскрытие было
// законным: кому выдали, когда, по какому запросу и в каком объёме. Без такого журнала
// доказывать нечем, а сама выгрузка выглядит как утечка.
//
// Почему отдельная таблица, а не audit_log, куда в этом проекте идут все истории:
//
//   - получатель и реквизиты запроса здесь не «детали события», а его суть: запись без
//     них бессмысленна, и обязательность должна держаться схемой, а не соглашением;
//   - журнал выдач - самостоятельный документ, который показывают проверяющему, и он
//     не подчиняется общим срокам хранения журналов: audit_log чистится уборкой,
//     а эта таблица - нет.
type PDDisclosure struct {
	ID int `json:"id"`

	// SubjectHMAC - свёртка документа, по которой собирали сведения. Само значение
	// документа в журнал не кладётся: он и так лежит в системе, а журнал выдач не
	// должен становиться вторым хранилищем паспортов.
	SubjectHMAC string `gorm:"size:64;index" json:"-"`
	// SubjectName - ФИО человека на момент выдачи. Нужно, чтобы журнал читался
	// человеком: по свёртке проверяющий ничего не поймёт.
	SubjectName string `gorm:"size:300" json:"subject_name"`

	// Recipient - кому выданы сведения: наименование органа или «субъекту лично».
	Recipient string `gorm:"size:300;not null" json:"recipient"`
	// RequestRef - реквизиты запроса: номер и дата письма, по которому выдано.
	RequestRef string `gorm:"size:300;not null" json:"request_ref"`
	// Basis - основание выдачи своими словами: запрос органа, обращение субъекта.
	Basis string `gorm:"type:text" json:"basis"`

	// Scope - объём выданного: сколько строк ушло по каждому разделу справки.
	// Строкой, а не числом: разделы меняются, а запись журнала обязана остаться
	// читаемой такой, какой её составили.
	Scope string `gorm:"type:text" json:"scope"`
	// Files - имена созданных файлов. Путь целиком не пишем: он привязан к машине,
	// а журнал переживает переезд.
	Files string `gorm:"type:text" json:"files"`

	// IssuedBy - кто выдал. Для консольной выдачи это не учётная запись системы, а
	// оператор сервера, поэтому текст, а не ссылка на пользователя.
	IssuedBy string `gorm:"size:200;not null" json:"issued_by"`
	// IssuedByUserID - учётная запись, если выдача шла через интерфейс.
	IssuedByUserID *int `gorm:"index" json:"issued_by_user_id,omitempty"`

	CreatedAt time.Time `gorm:"index" json:"created_at"`
}

func (PDDisclosure) TableName() string { return "pd_disclosures" }
