package models

import "time"

// UsedPassword - пароль, которым учётная запись уже пользовалась. Перечень нужен
// одному правилу: работник не может вернуться к паролю, который у него уже был.
//
// Хранится тот же хеш Argon2id, что лежит в users.password: сравнение идёт
// проверкой пароля против хеша, восстановить пароль из строки нельзя. Запись
// появляется при каждой смене и при заведении учётной записи - тогда в перечне
// всегда лежит и действующий пароль, и повтор текущего отсекается тем же
// сравнением, что и повтор давнего.
//
// Почему не audit_log, куда после #870 уходит вся история изменений. Это не
// журнал «кто и когда менял», а рабочий набор для проверки, и в общий журнал он
// не помещается по трём пунктам: содержимое audit_log показывают в истории
// сущности и выгружают в Excel, а это материал доступа; проверка перебирает
// последние записи одного человека, а не ищет по JSON общей таблицы; и уборка
// журнала по срокам хранения (#1614) молча сняла бы сам запрет, оставив правило
// без данных. Отсюда отдельная таблица, закрытая от чтения наружу.
//
// Каскад по пользователю обязателен: удалённая учётная запись не должна
// оставлять после себя набор своих хешей.
type UsedPassword struct {
	ID     int  `json:"id"`
	UserID int  `gorm:"index" json:"user_id"`
	User   User `gorm:"constraint:OnDelete:CASCADE" json:"-"`
	// PasswordHash - строка PHC ($argon2id$...), не сам пароль. json:"-" здесь
	// не украшение: наружу эта таблица не отдаётся ни одним методом.
	PasswordHash string    `gorm:"size:255" json:"-"`
	CreatedAt    time.Time `json:"created_at"`
}

func (UsedPassword) TableName() string { return "used_passwords" }
