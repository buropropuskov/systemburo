package normalize

import (
	"regexp"
	"sort"
	"strings"
	"unicode"
)

// orgLegalForms - полные организационно-правовые формы и их канонические аббревиатуры.
// Ключ дедупликации не должен различать "ООО Ромашка" и "Общество с ограниченной
// ответственностью Ромашка": для пропускного режима это одно юрлицо.
// Порядок значим - длинные формы идут раньше коротких, иначе "закрытое акционерное
// общество" схлопнется в "закрытое ао" вместо "зао".
var orgLegalForms = []struct{ full, short string }{
	{"федеральное государственное унитарное предприятие", "фгуп"},
	{"государственное бюджетное учреждение", "гбу"},
	{"муниципальное бюджетное учреждение", "мбу"},
	{"государственное унитарное предприятие", "гуп"},
	{"муниципальное унитарное предприятие", "муп"},
	{"общество с ограниченной ответственностью", "ооо"},
	{"непубличное акционерное общество", "нао"},
	{"закрытое акционерное общество", "зао"},
	{"открытое акционерное общество", "оао"},
	{"публичное акционерное общество", "пао"},
	{"индивидуальный предприниматель", "ип"},
	{"акционерное общество", "ао"},
}

// orgAbbrevOnlyForms - организационно-правовые формы, которые в наименованиях пишут
// только аббревиатурой: полной формы у них в orgLegalForms нет, но для смыслового ядра
// (OrgNameCore) они такой же служебный префикс, как ООО или ЗАО.
var orgAbbrevOnlyForms = []string{"чоп", "чоу", "ано", "нко", "тсж", "снт"}

// orgLegalFormTokens - все токены ОПФ: канонические аббревиатуры из orgLegalForms плюс
// те, что встречаются только сокращёнными. Строится при инициализации, чтобы список ОПФ
// оставался в одном месте.
var orgLegalFormTokens = map[string]bool{}

func init() {
	for _, form := range orgLegalForms {
		orgLegalFormTokens[form.short] = true
	}
	for _, short := range orgAbbrevOnlyForms {
		orgLegalFormTokens[short] = true
	}
}

// orgNameQuotes - кавычки всех начертаний, встречающиеся в наименованиях. В ключе
// заменяются ПРОБЕЛОМ (см. OrgName): «ООО Петрушка» и «ООО "Петрушка"» дают один ключ -
// именно этой парой написаний чаще всего и плодятся дубли, - а набранное без пробела
// «ООО"Петрушка» не склеивается в один токен и тоже находит ту же запись.
const orgNameQuotes = `"'«»„“”‘’`

// orgNameHyphens - тире всех видов. Приводятся к дефису, чтобы "Ромашка-Строй" и
// "Ромашка — Строй" не расходились по ключу.
const orgNameHyphens = `–—−`

// hyphenSpaces - пробелы вокруг дефиса. Схлопываются: наименование пишут и слитно
// через дефис, и с пробелами по краям, юрлицо при этом одно.
var hyphenSpaces = regexp.MustCompile(`\s*-\s*`)

// OrgName приводит наименование организации или компании к каноническому ключу
// дедупликации: нижний регистр, ё->е, латинские омоглифы->кириллица, кавычки как
// разделитель слов, отброшенные точки, канонизированная организационно-правовая форма,
// схлопнутые пробелы и дефисы. "ООО \"Петрушка\"", "ООО Петрушка", "ооо петрушка" и
// набранное без пробела «ООО"Петрушка» дают один ключ.
//
// Кавычка становится ПРОБЕЛОМ, а не выбрасывается: иначе «ооо"петрушка» склеивалось в
// «оообпетрушка»-подобный ключ, организационно-правовая форма не отделялась, и запись не
// находилась ни по наименованию с кавычками, ни без них.
//
// Результат хранится в колонке name_normalized и служит ключом поиска существующей
// записи при подаче заявки, поэтому эталон в базе и запрос обязаны нормализоваться
// ЭТОЙ ЖЕ функцией - иначе они разойдутся и дедупликация перестанет работать (#1437).
func OrgName(name string) string {
	lowered := strings.ToLower(name)

	var b strings.Builder
	b.Grow(len(lowered))
	for _, r := range lowered {
		switch {
		case strings.ContainsRune(orgNameQuotes, r):
			b.WriteRune(' ')
		case r == '.':
			continue
		case strings.ContainsRune(orgNameHyphens, r):
			b.WriteRune('-')
		case r == 'ё':
			b.WriteRune('е')
		default:
			if cyr, ok := latToCyrLower[r]; ok {
				r = cyr
			}
			b.WriteRune(r)
		}
	}

	// Схлопывание пробелов до замены форм: полные формы многословны и не совпадут
	// с образцом, если внутри наименования стоят двойные пробелы или перевод строки.
	cleaned := strings.Join(strings.Fields(b.String()), " ")
	for _, form := range orgLegalForms {
		cleaned = strings.ReplaceAll(cleaned, form.full, form.short)
	}
	cleaned = hyphenSpaces.ReplaceAllString(cleaned, "-")

	return strings.Join(strings.Fields(cleaned), " ")
}

// OrgNameCore возвращает смысловое ядро наименования - ключ OrgName без токенов
// организационно-правовой формы. Для подсказок сравнивать нужно именно ядра: человек
// печатает «максима», а в справочнике лежит «ООО "Максима Групп"», и общий префикс «ооо»
// у всех записей только размывает близость.
//
// Ядро НЕ хранится и ключом дедупликации не является: «ООО Ромашка» и «ЗАО Ромашка» -
// разные юрлица с одним ядром, поэтому оно годится для подсказки и не годится для
// автоматической привязки (#1437).
//
// Наименование, состоящее из одной ОПФ, ядра не имеет - для него возвращается сам ключ,
// иначе запись стала бы пустой строкой и перестала находиться.
func OrgNameCore(name string) string {
	key := OrgName(name)
	fields := strings.Fields(key)
	core := make([]string, 0, len(fields))
	for _, f := range fields {
		if orgLegalFormTokens[f] {
			continue
		}
		core = append(core, f)
	}
	if len(core) == 0 {
		return key
	}
	return strings.Join(core, " ")
}

// OrgLegalFormPattern возвращает регулярное выражение POSIX, которым SQL снимает токены
// ОПФ с хранимого name_normalized и получает то же ядро, что OrgNameCore даёт запросу.
// Список форм живёт только в Go: запрос получает паттерн параметром, поэтому два
// источника правды не заводятся.
//
// Токен ограничен ПРОБЕЛАМИ (или краями строки), а не границей слова POSIX: \m и \M
// считают границей и дефис, поэтому «ип-сервис» они резали до «-сервис», тогда как
// OrgNameCore режет по strings.Fields и оставляет наименование целым. Разъехавшиеся ядра
// молча ломают подсказку - совпадения просто перестают находиться.
//
// Хвостовой пробел не потребляется (lookahead), иначе у двух ОПФ подряд второй токен
// оставался бы без ведущего разделителя и не срезался: «ооо ип ромашка» -> «ромашка».
func OrgLegalFormPattern() string {
	tokens := make([]string, 0, len(orgLegalFormTokens))
	for token := range orgLegalFormTokens {
		tokens = append(tokens, token)
	}
	sort.Strings(tokens)
	return `(^|[[:space:]])(` + strings.Join(tokens, "|") + `)(?=[[:space:]]|$)`
}

// OrgNameMeaningless отвечает, что наименование не несёт содержания: в нём нет ни одной
// буквы и ни одной цифры - только кавычки, точки, дефисы или другая пунктуация.
//
// Ключ дедупликации (OrgName) такие наименования различает не всегда: кавычки и точки он
// выбрасывает и даёт пустой ключ, а дефис оставляет, поэтому «---» приходит с непустым
// ключом и выглядит валидным. Для подачи заявки разницы нет: ни из «"""», ни из «---»
// записи справочника быть не должно, иначе туда уезжает мусор от опечатки, с которым
// потом никто ничего не сделает (#1437).
func OrgNameMeaningless(name string) bool {
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return false
		}
	}
	return true
}
