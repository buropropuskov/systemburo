package normalize

import (
	"regexp"
	"strings"
	"unicode"
)

// Канонизация ОФОРМЛЕНИЯ наименования справочника (#1437). Отдельно от OrgName: тот
// считает служебный ключ дедупликации (нижний регистр, без кавычек), а здесь получается
// строка, которую видит человек и которая хранится в справочнике.
//
// Правило родилось из живого случая: заявку подали от «ооо "братишк» - строчная ОПФ,
// строчное название, незакрытая кавычка. Ключ дедупликации у такой записи корректный, и
// подача проходила, но в справочник уезжало именно то, что напечатали.

// orgLowercasePrefixes - служебные сокращения, которые в этом справочнике пишут
// строчными («м-н Летуаль», «р-н Мегобари»). Регистр им не правим, но и за название их
// не считаем: заглавная достаётся следующему слову.
var orgLowercasePrefixes = map[string]bool{"м-н": true, "р-н": true}

// OrgNameDisplay приводит наименование к аккуратному виду: схлопывает пробелы, закрывает
// непарную кавычку, поднимает токен организационно-правовой формы в верхний регистр
// («ооо» -> «ООО», «зао» -> «ЗАО») и делает заглавной первую букву названия.
//
// Чего функция НЕ делает намеренно:
//   - не понижает регистр остального текста: «ООО "ЭФКО-ЦР"» и «ОРППиПдБиРОП» должны
//     остаться как есть, а любое «умное» приведение к нижнему их искалечит;
//   - не сокращает полную форму («Общество с ограниченной ответственностью Ромашка»
//     остаётся полной) - это смена написания, а не оформления;
//   - не добавляет кавычки там, где их не было: половина справочника живёт без них
//     («ООО Демо-Партнёр», «АО Демо-Логистика»).
//
// Ключ дедупликации от канонизации не меняется (OrgName выбрасывает регистр, кавычки и
// повторные пробелы), поэтому канонизировать можно на любом шаге - до поиска записи или
// после. Инвариант закреплён тестом.
func OrgNameDisplay(name string) string {
	words := strings.Fields(splitGluedLegalForm(name))
	if len(words) == 0 {
		return ""
	}

	// Ведущие служебные токены: ОПФ поднимаем, бытовые сокращения оставляем как есть.
	// Заглавная достаётся первому слову, которое служебным не является.
	idx := 0
	for ; idx < len(words); idx++ {
		bare := strings.ToLower(strings.Trim(words[idx], orgNameQuotes+"."))
		if orgLegalFormTokens[bare] {
			words[idx] = strings.ToUpper(words[idx])
			continue
		}
		if orgLowercasePrefixes[bare] {
			continue
		}
		break
	}
	// Заглавную получает первое слово, в котором есть буква: у «ООО 585 золото» название
	// начинается числом, и капитализировать в нём нечего.
	for ; idx < len(words); idx++ {
		capitalized, ok := capitalizeFirstLetter(words[idx])
		words[idx] = capitalized
		if ok {
			break
		}
	}

	return closeDanglingQuote(strings.Join(words, " "))
}

// orgGluedLegalForm - организационно-правовая форма, набранная слитно с кавычкой:
// «ооо"бля», «ЗАО«Ромашка». Пробел между ними пропускают часто, и без разделения ОПФ не
// распознаётся: слово целиком не совпадает ни с одним токеном, поэтому в верхний регистр
// не уходит, а заглавная достаётся его первой букве («Ооо"бля»).
var orgGluedLegalForm = regexp.MustCompile(`^([\p{L}]+)([` + orgNameQuotes + `])`)

// splitGluedLegalForm вставляет пробел между ведущей ОПФ и кавычкой названия. Работает
// только когда слово до кавычки - известная форма: «Д"Артаньян» разделять нельзя, это
// само наименование.
func splitGluedLegalForm(name string) string {
	trimmed := strings.TrimSpace(name)
	m := orgGluedLegalForm.FindStringSubmatch(trimmed)
	if m == nil {
		return name
	}
	if !orgLegalFormTokens[strings.ToLower(m[1])] {
		return name
	}
	return m[1] + " " + trimmed[len(m[1]):]
}

// capitalizeFirstLetter поднимает первую БУКВУ слова, а не первый символ: у названия в
// кавычках первый символ - кавычка, и «"братишк» должно стать «"Братишк».
// Пустой второй результат значит, что букв в слове нет вовсе - тогда заглавная достаётся
// следующему слову («ооо 585 золото» -> «ООО 585 Золото»).
func capitalizeFirstLetter(word string) (string, bool) {
	runes := []rune(word)
	for i, r := range runes {
		if !unicode.IsLetter(r) {
			continue
		}
		runes[i] = unicode.ToUpper(r)
		return string(runes), true
	}
	return word, false
}

// orgClosingQuote - закрывающая кавычка для открывающей. Самопарные («"», «'») закрываются
// собой, у типографских закрывающая своя.
var orgClosingQuote = map[rune]rune{'«': '»', '„': '“', '“': '”', '‘': '’', '"': '"', '\'': '\''}

// closeDanglingQuote дописывает закрывающую кавычку, когда наименование в кавычках
// набрали и закрыть забыли: «ООО "Братишк» выглядит как обрезанное имя.
//
// Работает ТОЛЬКО в однозначном случае: во всей строке ровно одна кавычка любого
// начертания и стоит она там, где стоит открывающая - после начала строки или пробела и
// перед непробельным символом. Всё остальное остаётся как есть.
//
// Это осознанно узкое правило. Две попытки разобрать кавычки «по-умному» (сначала подсчёт
// пар, потом стек с ролями) на каждом раунде ревью давали новый вход, который функция
// ПОРТИЛА: то дописывала лишнюю кавычку к корректной русской вложенности, то удваивала
// одиночный лишний символ, то теряла идемпотентность на «ООО «"». Наименование с двумя и
// более кавычками почти всегда уже оформлено (в справочнике это «ООО "Максима Групп"»,
// «АО "Регионы-Энтертейнмент"», «ЧОП "АРЕС"»), а неоформленное лучше оставить человеку,
// чем испортить автоматом. Идемпотентность следует из правила структурно: сработало - в
// строке стало две кавычки и второй проход её не тронет; не сработало - строка не
// изменилась вовсе, и повторная проверка даст тот же ответ.
func closeDanglingQuote(name string) string {
	runes := []rune(name)
	quotes := 0
	position := -1
	for i, r := range runes {
		if _, isQuote := orgClosingQuote[r]; isQuote {
			quotes++
			position = i
			continue
		}
		// Закрывающая кавычка тоже считается: «ООО Братишка»» - не «одна кавычка».
		if isClosingQuote(r) {
			quotes++
			position = i
		}
	}
	if quotes != 1 || !opensAt(runes, position) {
		return name
	}
	return name + string(orgClosingQuote[runes[position]])
}

// isClosingQuote отвечает, является ли символ чьей-то закрывающей кавычкой.
func isClosingQuote(r rune) bool {
	for open, closing := range orgClosingQuote {
		if closing == r && open != r {
			return true
		}
	}
	return false
}

// opensAt отвечает, стоит ли кавычка в позиции открывающей: перед ней начало строки или
// пробел, после неё непробельный символ. «ООО "Братишк» - да; «ООО Братишка"» и
// «ООО Бра"тишка» - нет, там лишний символ, и дописывать ему пару значит портить имя.
func opensAt(runes []rune, i int) bool {
	if i < 0 || i+1 >= len(runes) || unicode.IsSpace(runes[i+1]) {
		return false
	}
	if _, isOpening := orgClosingQuote[runes[i]]; !isOpening {
		return false // одинокая закрывающая кавычка открытием не считается
	}
	return i == 0 || unicode.IsSpace(runes[i-1])
}
