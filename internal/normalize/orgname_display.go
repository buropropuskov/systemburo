package normalize

import (
	"strings"
	"unicode"
)

// Канонизация ОФОРМЛЕНИЯ наименования справочника (#1437). Отдельно от OrgName: тот
// считает служебный ключ дедупликации (нижний регистр, без кавычек), а здесь получается
// строка, которую видит человек и которая хранится в справочнике.
//
// Правило родилось из живого случая: заявку подали от «ооо "братишк» - строчная ОПФ,
// строчное название, незакрытая кавычка. Ключ дедупликации у такой записи корректный, и
// подача проходила, но в справочник уезжало именно то, что напечатали.

// orgLowercasePrefixes - служебные сокращения, которые в этом справочнике пишут
// строчными («м-н Летуаль», «р-н Мегобари»). Регистр им не правим, но и за название их
// не считаем: заглавная достаётся следующему слову.
var orgLowercasePrefixes = map[string]bool{"м-н": true, "р-н": true}

// OrgNameDisplay приводит наименование к аккуратному виду: схлопывает пробелы, закрывает
// непарную кавычку, поднимает токен организационно-правовой формы в верхний регистр
// («ооо» -> «ООО», «зао» -> «ЗАО») и делает заглавной первую букву названия.
//
// Чего функция НЕ делает намеренно:
//   - не понижает регистр остального текста: «ООО "ЭФКО-ЦР"» и «ОРППиПдБиРОП» должны
//     остаться как есть, а любое «умное» приведение к нижнему их искалечит;
//   - не сокращает полную форму («Общество с ограниченной ответственностью Ромашка»
//     остаётся полной) - это смена написания, а не оформления;
//   - не добавляет кавычки там, где их не было: половина справочника живёт без них
//     («ООО Демо-Партнёр», «АО Демо-Логистика»).
//
// Ключ дедупликации от канонизации не меняется (OrgName выбрасывает регистр, кавычки и
// повторные пробелы), поэтому канонизировать можно на любом шаге - до поиска записи или
// после. Инвариант закреплён тестом.
func OrgNameDisplay(name string) string {
	words := strings.Fields(name)
	if len(words) == 0 {
		return ""
	}

	// Ведущие служебные токены: ОПФ поднимаем, бытовые сокращения оставляем как есть.
	// Заглавная достаётся первому слову, которое служебным не является.
	idx := 0
	for ; idx < len(words); idx++ {
		bare := strings.ToLower(strings.Trim(words[idx], orgNameQuotes+"."))
		if orgLegalFormTokens[bare] {
			words[idx] = strings.ToUpper(words[idx])
			continue
		}
		if orgLowercasePrefixes[bare] {
			continue
		}
		break
	}
	if idx < len(words) {
		words[idx] = capitalizeFirstLetter(words[idx])
	}

	return closeDanglingQuote(strings.Join(words, " "))
}

// capitalizeFirstLetter поднимает первую БУКВУ слова, а не первый символ: у названия в
// кавычках первый символ - кавычка, и «"братишк» должно стать «"Братишк».
func capitalizeFirstLetter(word string) string {
	runes := []rune(word)
	for i, r := range runes {
		if !unicode.IsLetter(r) {
			continue
		}
		runes[i] = unicode.ToUpper(r)
		break
	}
	return string(runes)
}

// closeDanglingQuote дописывает недостающую закрывающую кавычку. Наименование в кавычках
// набирают быстро и закрыть их забывают - «ООО "Братишк» выглядит как обрезанное имя.
// Пары считаются по начертаниям: простые кавычки парны сами себе, типографские - парой.
func closeDanglingQuote(name string) string {
	if strings.Count(name, `"`)%2 == 1 {
		return name + `"`
	}
	for _, pair := range []struct{ open, close string }{
		{`«`, `»`}, {`„`, `“`}, {`“`, `”`}, {`‘`, `’`},
	} {
		if missing := strings.Count(name, pair.open) - strings.Count(name, pair.close); missing > 0 {
			return name + strings.Repeat(pair.close, missing)
		}
	}
	return name
}
