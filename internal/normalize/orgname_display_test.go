package normalize

import "testing"

func TestOrgNameDisplay(t *testing.T) {
	cases := []struct{ name, in, want string }{
		// Живой случай, из которого выросло правило.
		{"строчная ОПФ и незакрытая кавычка", `ооо "братишк`, `ООО "Братишк"`},
		{"строчная ОПФ без кавычек", "ооо братишка", "ООО Братишка"},
		{"ОПФ не только ООО", "зао ромашка", "ЗАО Ромашка"},
		{"ИП", "ип иванов и.и.", "ИП Иванов и.и."},
		{"ЧОП пишут только аббревиатурой", `чоп "арес"`, `ЧОП "Арес"`},
		{"бюджетное учреждение", "гбу городская служба", "ГБУ Городская служба"},
		{"две формы подряд", "ооо чоп охрана", "ООО ЧОП Охрана"},

		// Наименование без ОПФ - заглавная достаётся первому слову.
		{"без ОПФ", "отдел аренды", "Отдел аренды"},
		{"служебное сокращение остаётся строчным", "м-н летуаль", "м-н Летуаль"},
		{"район", "р-н мегобари", "р-н Мегобари"},

		// Уже аккуратные наименования канонизация не трогает.
		{"аббревиатура в названии", `ООО "ЭФКО-ЦР"`, `ООО "ЭФКО-ЦР"`},
		{"смешанный регистр не понижается", "ОРППиПдБиРОП", "ОРППиПдБиРОП"},
		{"полная форма остаётся полной", "Общество с ограниченной ответственностью Ромашка", "Общество с ограниченной ответственностью Ромашка"},
		{"кавычки на месте", `ООО "Максима Групп"`, `ООО "Максима Групп"`},

		// Пробелы и типографские кавычки.
		{"повторные пробелы", "ооо   ромашка   строй", "ООО Ромашка строй"},
		{"обрамляющие пробелы", "  ооо ромашка  ", "ООО Ромашка"},
		{"незакрытая ёлочка", `ооо «братишк`, `ООО «Братишк»`},
		{"парные ёлочки не трогаем", `ООО «Братишка»`, `ООО «Братишка»`},
		{"пустая строка", "   ", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := OrgNameDisplay(c.in); got != c.want {
				t.Errorf("OrgNameDisplay(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

// Канонизация оформления не имеет права менять ключ дедупликации: иначе одно и то же
// юрлицо, введённое до и после канонизации, разъедется по двум записям справочника.
func TestOrgNameDisplayKeepsKey(t *testing.T) {
	inputs := []string{
		`ооо "братишк`, "ооо братишка", "зао ромашка", `чоп "арес"`, "м-н летуаль",
		"отдел аренды", "ОРППиПдБиРОП", `ООО "ЭФКО-ЦР"`, "ооо   ромашка   строй",
		"Общество с ограниченной ответственностью Ромашка", `ооо «братишк`, "ип иванов и.и.",
	}
	for _, in := range inputs {
		if before, after := OrgName(in), OrgName(OrgNameDisplay(in)); before != after {
			t.Errorf("ключ уехал: OrgName(%q) = %q, а после канонизации %q", in, before, after)
		}
	}
}

// Повторный проход ничего не меняет: канонизация идёт на каждом сохранении, и запись,
// открытая и сохранённая без правок, обязана остаться прежней.
func TestOrgNameDisplayIdempotent(t *testing.T) {
	inputs := []string{
		`ооо "братишк`, "м-н летуаль", "отдел аренды", `ООО "Максима Групп"`,
		"ОРППиПдБиРОП", "ип петров п.п.", `ЧОП "АРЕС"`,
	}
	for _, in := range inputs {
		once := OrgNameDisplay(in)
		if twice := OrgNameDisplay(once); twice != once {
			t.Errorf("не идемпотентно: %q -> %q -> %q", in, once, twice)
		}
	}
}

// Наименования, уже лежащие в справочнике, канонизация менять не должна: иначе открытая
// и сохранённая без правок запись поедет, а история получит ложное «переименована».
// Набор снят с боевого справочника staging (26.07.2026).
func TestOrgNameDisplayKeepsExistingDirectory(t *testing.T) {
	existing := []string{
		"АО Демо-Логистика", "Бюро пропусков", "ИП Иванов И.И.", "ООО Демо-Партнёр",
		"ОРППиПдБиРОП", "Отдел аренды", "Отдел контроля доступа", "Технический департамент",
		"м-н Летуаль", "м-н Фамилия", "р-н Мегобари",
		`АО "Регионы-Энтертейнмент"`, "АО Демо-Транса", "ИП Петров П.П.", `ООО "Максима Групп"`,
		`ООО "Парк развлечений"`, `ООО "Победа"`, `ООО "РПС"`, `ООО "ЭФКО-ЦР"`, "ООО Демо-Сервис",
		`ЧОП "АРЕС"`,
	}
	for _, name := range existing {
		if got := OrgNameDisplay(name); got != name {
			t.Errorf("существующее наименование изменилось: %q -> %q", name, got)
		}
	}
}
