package normalize

import (
	"strings"
	"testing"
)

// Транслитерация поиска (#2414): человек, знающий заведение как «Траттория», обязан
// находить запись «La Trattoria», и наоборот. Написание неоднозначно, поэтому вариантов
// несколько - проверяем, что нужный среди них есть.
func TestTranslit(t *testing.T) {
	содержит := func(варианты []string, искомое string) bool {
		for _, v := range варианты {
			if strings.Contains(v, искомое) {
				return true
			}
		}
		return false
	}

	tests := []struct {
		имя    string
		вход   string
		ждём   string
		почему string
	}{
		{"кириллица к латинице как на вывеске", "траттория", "trattoria",
			"«я» в конце пишут как «a», а не «ya» - ради этого всё и заводилось"},
		{"кириллица к латинице по документам", "траттория", "trattoriya",
			"вторая схема тоже нужна: в паспортах пишут именно так"},
		{"потерянное удвоение", "траттория", "tratoria",
			"удвоенные согласные теряют чаще всего"},
		{"латиница к кириллице", "sergey", "сергей",
			"сотрудник, заведённый латиницей, ищется по-русски"},
		{"латиница к кириллице через ia", "mariia", "мария", ""},
		{"многобуквенные сочетания не рассыпаются", "shchukin", "щукин",
			"«shch» - это «щ», а не «с»+«х»+«ч»"},
		{"х как kh и как h", "харитонов", "kharitonov", ""},
		{"х во второй схеме", "харитонов", "haritonov", ""},
		{"ц как ts и как c", "цветков", "tsvetkov", ""},
		{"ц во второй схеме", "цветков", "cvetkov", ""},
	}

	for _, tt := range tests {
		t.Run(tt.имя, func(t *testing.T) {
			got := Translit(tt.вход)
			if !содержит(got, tt.ждём) {
				t.Errorf("Translit(%q) = %v, среди вариантов нет %q. %s", tt.вход, got, tt.ждём, tt.почему)
			}
		})
	}
}

// Вариантов должно быть мало: каждый уходит в запрос отдельным условием и множится
// на число колонок. Декартово произведение по спорным буквам дало бы сотни строк.
func TestTranslit_VariantCountStaysSmall(t *testing.T) {
	for _, s := range []string{"траттория", "щукин", "александрович", "sergey", "la trattoria"} {
		if n := len(Translit(s)); n > 6 {
			t.Errorf("Translit(%q) дал %d вариантов - слишком много для запроса", s, n)
		}
	}
}

func TestTranslit_EmptyAndNoise(t *testing.T) {
	if got := Translit(""); got != nil {
		t.Errorf("пустой ввод обязан давать пустой результат, получено %v", got)
	}
	if got := Translit("   "); got != nil {
		t.Errorf("пробелы - тот же пустой ввод, получено %v", got)
	}
	// Оригинал в варианты не попадает: он и так уходит в запрос отдельно.
	for _, v := range Translit("траттория") {
		if v == "траттория" {
			t.Error("оригинал не должен дублироваться в вариантах")
		}
	}
}

// Короткие фрагменты не транслитерируются: «рга» в латинице становится «rga», а это
// кусок слова «Organization» - поиск начинал тянуть все записи тестовой организации.
func TestTranslit_ShortQueriesSkipped(t *testing.T) {
	for _, s := range []string{"рга", "ким", "abc", "ab", "я"} {
		if got := Translit(s); got != nil {
			t.Errorf("Translit(%q) = %v, короткие фрагменты транслитерировать нельзя", s, got)
		}
	}
	if got := Translit("серг"); got == nil {
		t.Error("четыре символа - уже рабочая длина, варианты обязаны быть")
	}
}
