package services

// bureauWorkingDuration -- рабочие секунды Бюро между двумя моментами по его
// расписанию (аналитика обработки заявок #1251). Зеркалит форму durationBetween
// (from, to -- SQL-выражения колонок, порядок «позже минус раньше»), но вместо
// календарной разницы считает только время, когда Бюро реально работает: ночь и
// выходные из длительности выпадают. Рабочее время инкапсулировано в SQL-функции
// bureau_working_seconds (installSQLFunctions в migrate.go).
//
// Календарный фолбэк срабатывает в ДВУХ случаях, и оба про одно: рабочее время не
// должно превращать реальную длительность в ноль.
//
//  1. График Бюро не заведён вовсе (в bureau_time_slots нет активных слотов):
//     расписание настраивается вручную в админке и сидами не создаётся, поэтому на
//     неконфигурированном окружении все этапы дали бы 0.
//  2. График заведён, но интервал события с ним НЕ пересекается (bureau_working_seconds
//     = 0 при ненулевой календарной разнице). Так бывает на частично заполненном
//     расписании: staging с единственным слотом «четверг 08:00-22:00» показывал
//     согласующим с 35 и 14 голосами «время реакции 0 секунд» -- все их события
//     пришлись на субботу, среду и вторник. Ноль здесь неотличим от «согласовал
//     мгновенно», то есть рейтинг хвалил самых медленных.
//
// NULLIF гасит именно нулевое пересечение, COALESCE подставляет календарную разницу.
// Легитимный ноль (согласовали в ту же секунду в рабочее время) при этом не ломается:
// календарная разница там тоже 0. NULL-аргумент остаётся NULL в обеих ветках, и
// строка по-прежнему выпадает из агрегата, а не превращается в число.
//
// Выражение -- скалярный CASE, поэтому подставляется внутрь AVG/PERCENTILE_CONT как
// и durationBetween. Обе ветки CASE приводятся к numeric (bigint функции + numeric
// EXTRACT), итог агрегата всё равно кастится в bigint durationRound'ом.
func bureauWorkingDuration(from, to string) string {
	calendar := durationBetween(from, to)
	working := "bureau_working_seconds(" + from + ", " + to + ")"
	return "CASE WHEN EXISTS (SELECT 1 FROM bureau_time_slots WHERE is_active) " +
		"THEN COALESCE(NULLIF(" + working + ", 0), " + calendar + ") " +
		"ELSE " + calendar + " END"
}
