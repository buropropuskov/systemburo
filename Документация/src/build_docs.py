def clean_cell(text):
    """Текст ячейки без разметки: в PDF попадает именно он."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return re.sub(r"\s+", " ", text).strip()



def cell_probe(text):
    """Кусок ячейки, который заведомо лежит на одной строке колонки.

    Ячейка переносится внутри своей колонки, и в текстовом слое PDF между её
    частями оказывается текст соседних колонок. Поэтому берём первое слово, а
    если оно слишком короткое для поиска - добавляем следующее.
    """
    words = clean_cell(text).split()
    if not words:
        return ""
    probe = words[0]
    for word in words[1:]:
        if len(probe) >= 6:
            break
        probe = f"{probe} {word}"
    return probe


def table_probes(headers, rows):
    """Пробы строк таблицы: по одной на ячейку, в порядке колонок.

    Строка видна на странице, если нашлась хотя бы одна её проба. Одной первой
    ячейки мало: длинный идентификатор вроде UPLOAD_ALLOWED_IMAGE_TYPES не
    помещается в ширину колонки и в текстовом слое разорван переносом, отчего
    строка выглядит непоместившейся.

    Пробу, встречающуюся в таблице дважды, выбрасываем: типовые формулировки
    соседних колонок («Как часто», «Разрешённые типы») совпадают у разных строк,
    и строка засчитывалась найденной по тексту предыдущей. Совпадающие с шапкой
    - туда же: шапка повторяется на каждой странице.
    """
    raw = [[cell_probe(c) for c in row] for row in rows]
    times = {}
    for row in raw:
        for probe in row:
            if probe:
                times[probe] = times.get(probe, 0) + 1
    head = {cell_probe(h) for h in headers}
    return [[p for p in row if p and times[p] == 1 and p not in head] for row in raw]


def find_probe(haystack, probe, cursor):
    """Позиция за концом пробы или -1. Проба ищется целым словом.

    Без границ слова короткое значение вроде «5m» находится внутри «15m»
    соседней строки, и таблица выглядит уместившейся.
    """
    match = re.compile(rf"(?<!\w){re.escape(probe)}(?!\w)").search(haystack, cursor)
    return match.end() if match else -1


def split_rows(rows, breaks):
    """Разрезать строки таблицы в местах, где страница её разрывает."""
    if not breaks:
        return [rows]
    chunks, start = [], 0
    for point in breaks:
        if 0 < point < len(rows):
            chunks.append(rows[start:point])
            start = point
    chunks.append(rows[start:])
    return [c for c in chunks if c]


def rows_in_table(tables_meta, number):
    """Сколько строк данных в таблице: точка разреза за этой границей ничего не режет."""
    for meta in tables_meta:
        if meta["number"] == number:
            return len(meta["row_probes"])
    return 0


def next_break_in_tail(cfg, tables_meta, number, known):
    """Место следующего разрыва в уже разрезанной таблице.

    Длинная таблица не укладывается и в две части: приложение параметров рвётся
    после первой подписи продолжения ещё раз, а подбор ставит одну точку и
    считает работу сделанной. Ищем от последней подписи продолжения, отсчитывая
    строки от последнего разреза, - возвращаем точку в тех же координатах, что
    и первая, то есть от начала таблицы.
    """
    meta = next((m for m in tables_meta if m["number"] == number), None)
    if not meta:
        return None
    pages = subprocess.run(
        ["pdftotext", "-layout", doc_path(cfg, ".pdf"), "-"],
        capture_output=True, text=True, check=True,
    ).stdout.split("\f")
    flat = [re.sub(r"\s+", " ", pg) for pg in pages]

    marker = f"Продолжение таблицы {number}"
    tail = [i for i, pg in enumerate(flat) if marker in pg]
    if not tail:
        return None

    page = flat[tail[-1]]
    cursor = page.rfind(marker) + len(marker)
    for probe in meta["head_probes"]:
        at = find_probe(page, probe, cursor)
        if at >= 0:
            cursor = at

    probes = meta["row_probes"]
    pos = known[-1]
    while pos < len(probes):
        hit = -1
        for probe in probes[pos]:
            hit = find_probe(page, probe, cursor)
            if hit >= 0:
                break
        if hit < 0 and probes[pos]:
            break
        cursor = hit if hit >= 0 else cursor
        pos += 1
    return pos if pos < len(probes) else None


def find_first_unsplit_break(cfg, tables_meta, handled):
    """Найти первую сверху таблицу, которую страница рвёт, и место разрыва.

    Обрабатываем строго по одной сверху вниз. Вёрстка однонаправленна: содержимое
    ниже не влияет на положение того, что выше, поэтому уже зафиксированное
    разбиение от последующих не сдвинется. Попытка разобрать все таблицы за один
    проход не сходится: разбиение верхней таблицы смещает все нижние.

    Уместившиеся таблицы намеренно не запоминаются: разбиение вышележащей сдвигает
    вёрстку, и таблица, которая помещалась, начинает рваться.
    """
    pages = subprocess.run(
        ["pdftotext", "-layout", doc_path(cfg, ".pdf"), "-"],
        capture_output=True, text=True, check=True,
    ).stdout.split("\f")
    flat = [re.sub(r"\s+", " ", pg) for pg in pages]

    for meta in tables_meta:
        number = meta["number"]
        if number in handled:
            continue
        probes = meta["row_probes"]
        if len(probes) < 2:
            dbg(f"таблица {number}: строк {len(probes)}, резать нечего")
            continue

        marker = f"Таблица {number} "
        start = next((i for i, pg in enumerate(flat) if marker in pg), None)
        if start is None:
            dbg(f"таблица {number}: подпись не найдена в PDF")
            continue

        page = flat[start]
        cursor = page.find(marker) + len(marker)
        # Шапка повторяет слова первой колонки: у таблицы разделения журналов
        # и заголовок, и обе строки начинаются со слова «Журнал». Поиск строк
        # данных начинаем за шапкой, иначе её слова засчитываются за строки и
        # разорванная таблица выглядит уместившейся.
        for probe in meta["head_probes"]:
            at = find_probe(page, probe, cursor)
            if at >= 0:
                cursor = at

        pos = 0
        while pos < len(probes):
            hit = -1
            for probe in probes[pos]:
                hit = find_probe(page, probe, cursor)
                if hit >= 0:
                    break
            if hit < 0 and probes[pos]:
                break
            cursor = hit if hit >= 0 else cursor
            pos += 1

        if pos == 0:
            dbg(f"таблица {number}: на стр. {start + 1} не нашлась ни одна строка")
            continue
        if pos < len(probes):
            # таблица не поместилась: строка pos начинается уже на следующей странице
            dbg(f"таблица {number}: разрыв на стр. {start + 1}, строк {len(probes)}, "
                f"точка {pos} (первая ненайденная строка: {probes[pos]!r})")
            return number, [pos]
    return None, None



def split_verdict(cfg, number, tail=False):
    """Оценить разрез таблицы по готовому PDF и подсказать, куда двигать точку.

    Подпись продолжения сама занимает строку, поэтому попадание с первого раза
    не гарантировано, а оценка по текстовому слою и вовсе приблизительная.
    Зато по вёрстке однозначно видно, в какую сторону ошиблись:

    - подпись в начале страницы - разрез там, где страница и рвёт таблицу;
    - подпись висит на странице, где таблица началась, - остаток уместился
      целиком, разрез слишком ранний, резать надо ниже;
    - подпись на следующей странице, но не сверху - первая часть сама не
      поместилась, резать надо выше.
    """
    pages = subprocess.run(
        ["pdftotext", "-layout", doc_path(cfg, ".pdf"), "-"],
        capture_output=True, text=True, check=True,
    ).stdout.split("\f")

    head = next((i for i, pg in enumerate(pages) if f"Таблица {number} " in pg), None)
    # При двух разрезах первая подпись уже стоит верно, и оценивать надо
    # последнюю: иначе подбор второй точки всегда получает «ok».
    order = reversed(list(enumerate(pages))) if tail else enumerate(pages)
    for pageno, page in order:
        lines = [ln for ln in page.splitlines() if ln.strip()]
        for idx, line in enumerate(lines):
            if f"Продолжение таблицы {number}" in line:
                dbg(f"подпись продолжения {number}: стр. {pageno + 1}, строка {idx}")
                if idx == 0:
                    return "ok"
                return "early" if head is not None and pageno <= head else "late"
    dbg(f"подпись продолжения {number}: в PDF не найдена")
    return "none"


def add_table(doc, headers, rows, widths=None):
    """Таблица целиком либо её часть.

    Части разрезанной таблицы получают общую сетку колонок: ширины считаются
    по всем строкам сразу и передаются снаружи. Иначе продолжение вымеряется
    по своему куску и выглядит другой таблицей - у разделения журналов первая
    колонка на одной странице вдвое уже, чем на следующей.
    """
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    fixed_layout(table)
    if widths is None:
        widths = column_widths(headers, rows)

    head_cells = table.rows[0].cells
    for i, title in enumerate(headers):
        shade_cell(head_cells[i], HEAD_FILL)
        para = head_cells[i].paragraphs[0]
        para.paragraph_format.first_line_indent = Mm(0)
        para.paragraph_format.line_spacing = 1.0
        para.paragraph_format.space_after = Pt(0)
        para.alignment = WD_ALIGN_PARAGRAPH.LEFT
        add_inline(para, title, size=12)
        for run in para.runs:
            run.font.bold = True
    header_row_repeat(table.rows[0])

    for row in rows:
        cells = table.add_row().cells
        no_split_row(table.rows[-1])
        # строка-форма: заполняется от руки, поэтому ей нужна высота
        if any((row[i] if i < len(row) else "").strip() == "~" for i in range(len(headers))):
            set_row_height(table.rows[-1], 2.6)
        else:
            filled = sum(1 for i in range(len(headers)) if i < len(row) and row[i].strip())
            if filled == 0 or (filled <= 1 and len(headers) >= 2):
                set_row_height(table.rows[-1], 1.2)
        for i in range(len(headers)):
            para = cells[i].paragraphs[0]
            para.paragraph_format.first_line_indent = Mm(0)
            para.paragraph_format.line_spacing = 1.0
            para.paragraph_format.space_after = Pt(0)
            para.alignment = WD_ALIGN_PARAGRAPH.LEFT
            text = row[i] if i < len(row) else ""
            # «~» в исходнике - просторное поле под запись от руки
            add_inline(para, "" if text.strip() == "~" else text, size=12)

    apply_grid(table, widths)
    for r in table.rows:
        for i, w in enumerate(widths):
            r.cells[i].width = Cm(w)

    # Таблица-форма состоит из пустых граф, распознать её разрыв по содержимому
    # нельзя. Поэтому держим её единым блоком: не поместилась - уходит целиком
    # на следующую страницу.
    empty = sum(1 for row in rows for i in range(len(headers))
                if not (row[i] if i < len(row) else "").strip())
    if rows and empty >= len(rows) * len(headers) * 0.5:
        for r in table.rows[:-1]:
            for cell in r.cells:
                for para in cell.paragraphs:
                    para.paragraph_format.keep_with_next = True

    spacer = doc.add_paragraph()
    spacer.paragraph_format.first_line_indent = Mm(0)
    spacer.paragraph_format.space_after = Pt(0)
    spacer.paragraph_format.line_spacing = 1.0
    set_font(spacer.add_run(""), size=6)


# Кегль листинга подбирается по самой длинной строке. Courier New занимает 0.6
# кегля на знак, поэтому в поле листинга (текст 16.5 см минус отступы 4 и 2 мм)
# при 10 pt помещается 75 знаков: всё, что шире, Word переносит, и вывод команды,
# разложенный по столбцам, рассыпается - в перечне копий колонка с именем файла
# уезжала на отдельную строку. Ниже 6.5 pt не опускаемся: неразборчиво.
CODE_FIELD_MM = 165 - 4 - 2
CODE_CHARS_X_PT = CODE_FIELD_MM * 72 / (0.6 * 25.4)


def code_font_size(lines):
    widest = max((len(line) for line in lines), default=1)
    if widest <= CODE_CHARS_X_PT / 10:
        return 10
    fits = CODE_CHARS_X_PT / widest
    return max(6.5, int(fits * 2) / 2)


def add_code_block(doc, lines):
    para = doc.add_paragraph()
    pf = para.paragraph_format
    pf.first_line_indent = Mm(0)
    pf.left_indent = Mm(4)
    pf.right_indent = Mm(2)
    pf.line_spacing = 1.0
    pf.space_before = Pt(2)
    pf.space_after = Pt(8)
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf.keep_together = True
    shade_paragraph(para, CODE_FILL)
    border_paragraph(para)
    size = code_font_size(lines)
    for i, line in enumerate(lines):
        if i:
            para.add_run().add_break()
        set_font(para.add_run(line), name=MONO, size=size)


def add_callout(doc, kind, lines):
    """Блок повышенного внимания: заливка, толстая полоса слева, подпись типа."""
    fill, accent = CALLOUTS[kind]
    table = doc.add_table(rows=1, cols=1)
    table.autofit = False
    fixed_layout(table)
    apply_grid(table, [TEXT_WIDTH_CM])
    cell = table.cell(0, 0)
    cell.width = Cm(TEXT_WIDTH_CM)
    shade_cell(cell, fill)

    borders = OxmlElement("w:tcBorders")
    for edge, width, color in (
        ("left", "24", accent), ("top", "4", fill),
        ("bottom", "4", fill), ("right", "4", fill),
    ):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), width)
        el.set(qn("w:color"), color)
        borders.append(el)
    cell._tc.get_or_add_tcPr().append(borders)

    # Блок читается как единое предупреждение, разрыв между страницами его ломает.
    no_split_row(table.rows[0])

    first = cell.paragraphs[0]
    first.paragraph_format.first_line_indent = Mm(0)
    first.paragraph_format.line_spacing = 1.2
    first.paragraph_format.space_after = Pt(0)
    set_font(first.add_run(kind + ". "), size=13, bold=True,
             color=RGBColor.from_string(accent))
    # После точки в маркере идёт новое предложение, поэтому первая буква заглавная
    # независимо от того, как написано в исходном тексте.
    head = lines[0]
    if head and head[0].islower():
        head = head[0].upper() + head[1:]
    add_inline(first, head, size=13)

    for extra in lines[1:]:
        para = cell.add_paragraph()
        para.paragraph_format.first_line_indent = Mm(0)
        para.paragraph_format.line_spacing = 1.2
        para.paragraph_format.space_before = Pt(4)
        para.paragraph_format.space_after = Pt(0)
        add_inline(para, extra, size=13)

    spacer = doc.add_paragraph()
    spacer.paragraph_format.first_line_indent = Mm(0)
    spacer.paragraph_format.space_after = Pt(0)
    spacer.paragraph_format.line_spacing = 1.0
    set_font(spacer.add_run(""), size=6)


def image_size_cm(path):
    """Размер картинки на листе в сантиметрах.

    Ширина считается от числа точек при печатном разрешении, а не задаётся
    равной ширине текста: снимок мелкого элемента, растянутый на всю ширину
    полосы, выглядит размытым, тогда как поставленный в свой размер остаётся
    чётким. Широкий снимок ужимается до ширины текста, высокий - до предельной
    высоты, иначе он молча выпирает за поле листа.
    """
    image = DocxImage.from_file(path)
    width = image.px_width / (image.horz_dpi or 72) * 2.54
    height = image.px_height / (image.vert_dpi or 72) * 2.54
    scale = min(TEXT_WIDTH_CM / width, MAX_IMAGE_HEIGHT_CM / height, 1.0)
    return width * scale, height * scale


def add_image(doc, path, caption_text):
    if not os.path.exists(path):
        raise FileNotFoundError(f"не найдено изображение: {path}")
    width_cm, height_cm = image_size_cm(path)
    doc.add_picture(path, width=Cm(width_cm), height=Cm(height_cm))
    pic = doc.paragraphs[-1]
    pic.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pic.paragraph_format.first_line_indent = Mm(0)
    pic.paragraph_format.space_before = Pt(6)
    pic.paragraph_format.space_after = Pt(2)
    pic.paragraph_format.keep_with_next = True
    add_caption(doc, caption_text, above=False)


def parse_markdown(md_text):
    blocks = []
    lines = md_text.split("\n")
    i = 0
    pending_caption = None

    while i < len(lines):
        raw = lines[i]
        stripped = raw.strip()

        if stripped == "<!-- PAGEBREAK -->":
            blocks.append(("pagebreak", None))
            i += 1
            continue

        if stripped == "<!-- SPACER -->":
            blocks.append(("spacer", None))
            i += 1
            continue

        if not stripped:
            i += 1
            continue

        # подпись к следующему объекту: «Таблица: ...» либо «Листинг: ...»
        cap = re.match(r"^(Таблица|Листинг):\s+(.+)$", stripped)
        if cap:
            pending_caption = (cap.group(1), cap.group(2).strip())
            i += 1
            continue

        # блок внимания: «> ВАЖНО: текст», продолжение строками «> ...»
        callout = re.match(r"^>\s*(ОПАСНО|ВАЖНО|ПРИМЕЧАНИЕ):\s*(.*)$", stripped)
        if callout:
            kind = callout.group(1)
            body = [callout.group(2).strip()]
            i += 1
            while i < len(lines) and lines[i].strip().startswith(">"):
                body.append(lines[i].strip().lstrip("> ").strip())
                i += 1
            blocks.append(("callout", (kind, [b for b in body if b])))
            continue

        if stripped.startswith("```"):
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            blocks.append(("code", (code, pending_caption)))
            pending_caption = None
            continue

        heading = re.match(r"^(#{1,4})\s+(.*)$", stripped)
        if heading:
            blocks.append(("heading", (len(heading.group(1)), heading.group(2).strip())))
            i += 1
            continue

        image = re.match(r"^!\[(.*?)\]\((.+?)\)$", stripped)
        if image:
            blocks.append(("image", (image.group(2), image.group(1))))
            i += 1
            continue

        if stripped.startswith("|") and i + 1 < len(lines) and re.match(
            r"^\|[\s:|-]+\|$", lines[i + 1].strip()
        ):
            headers = split_table_row(lines[i])
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(split_table_row(lines[i]))
                i += 1
            blocks.append(("table", (headers, rows, pending_caption)))
            pending_caption = None
            continue

        bullet = re.match(r"^([-*])\s+(.*)$", stripped)
        if bullet:
            items = []
            while i < len(lines):
                m = re.match(r"^([-*])\s+(.*)$", lines[i].strip())
                if not m or not lines[i].strip():
                    break
                text = m.group(2)
                i += 1
                while i < len(lines) and lines[i].startswith("  ") and not re.match(
                    r"^\s*([-*]|\d+\.)\s", lines[i]
                ):
                    text += " " + lines[i].strip()
                    i += 1
                items.append(text)
            blocks.append(("bullets", items))
            continue

        numbered = re.match(r"^\d+\.\s+(.*)$", stripped)
        if numbered:
            items = []
            while i < len(lines):
                m = re.match(r"^\d+\.\s+(.*)$", lines[i].strip())
                if not m or not lines[i].strip():
                    break
                text = m.group(1)
                i += 1
                while i < len(lines) and lines[i].startswith("   ") and not re.match(
                    r"^\s*(\d+\.|[-*])\s", lines[i]
                ):
                    text += " " + lines[i].strip()
                    i += 1
                items.append(text)
            blocks.append(("numbers", items))
            continue

        para = [stripped]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(
            r"^(#{1,4}\s|```|\||[-*]\s|\d+\.\s|!\[|>\s*(ОПАСНО|ВАЖНО|ПРИМЕЧАНИЕ):|(Таблица|Листинг):\s)",
            lines[i].strip(),
        ):
            para.append(lines[i].strip())
            i += 1
        blocks.append(("para", " ".join(para)))

    return blocks


def section_prefix(title):
    """Префикс нумерации объектов: «5» из «5. Требования», «А» из «Приложение А»."""
    app = re.match(r"^Приложение\s+([А-ЯA-Z])", title)
    if app:
        return app.group(1)
    num = re.match(r"^(\d+)\.", title)
    return num.group(1) if num else None


def render(doc, blocks, toc_titles, splitmap=None, tables_meta=None):
    counters = {"table": 0, "figure": 0, "listing": 0}
    prefix = "1"
    splitmap = splitmap or {}

    for kind, payload in blocks:
        if kind == "pagebreak":
            doc.add_page_break()

        elif kind == "spacer":
            gap = doc.add_paragraph()
            gap.paragraph_format.first_line_indent = Mm(0)
            gap.paragraph_format.space_after = Pt(0)
            set_font(gap.add_run(""), size=14)

        elif kind == "heading":
            level, text = payload
            if level == 1:
                new_prefix = section_prefix(text)
                if new_prefix:
                    prefix = new_prefix
                    counters = {"table": 0, "figure": 0, "listing": 0}
            para = doc.add_heading(level=min(level, 4))
            para.paragraph_format.first_line_indent = Mm(0)
            set_font(para.add_run(text), size=HEADING_SIZE[min(level, 4)], bold=True)
            if level <= 2:
                toc_titles.append((level, text))

        elif kind == "para":
            para = doc.add_paragraph()
            # Строка с местом под запись от руки: выравнивание по ширине растянуло
            # бы её и линия разъехалась, поэтому прижимаем к левому краю.
            if "___" in payload:
                para.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
                para.paragraph_format.first_line_indent = Mm(0)
                para.paragraph_format.space_before = Pt(6)
            add_inline(para, payload)

        elif kind == "bullets":
            for item in payload:
                add_list_item(doc, "\u2022", item)

        elif kind == "numbers":
            for pos, item in enumerate(payload, 1):
                add_list_item(doc, f"{pos}.", item)

        elif kind == "callout":
            add_callout(doc, payload[0], payload[1])

        elif kind == "code":
            code, cap = payload
            if cap:
                counters["listing"] += 1
                add_caption(doc, f"Листинг {prefix}.{counters['listing']} \u2014 {cap[1]}")
            add_code_block(doc, code)

        elif kind == "table":
            headers, rows, cap = payload
            if cap:
                counters["table"] += 1
                number = f"{prefix}.{counters['table']}"
                if tables_meta is not None:
                    tables_meta.append({"number": number,
                                        "head_probes": [cell_probe(h) for h in headers],
                                        "row_probes": table_probes(headers, rows)})
                widths = column_widths(headers, rows)
                for idx, chunk in enumerate(split_rows(rows, splitmap.get(number))):
                    if idx == 0:
                        add_caption(doc, f"Таблица {number} \u2014 {cap[1]}")
                    else:
                        # Принудительный разрыв не нужен: часть выше закончилась на
                        # границе листа, а подпись держится за своей таблицей.
                        add_caption(doc, f"Продолжение таблицы {number}")
                    add_table(doc, headers, chunk, widths)
            else:
                add_table(doc, headers, rows)

        elif kind == "image":
            path, caption = payload
            if not os.path.isabs(path):
                path = os.path.join(BASE_DIR, path)
            counters["figure"] += 1
            add_image(doc, path, f"Рисунок {prefix}.{counters['figure']} \u2014 {caption}")


def render_toc(doc, entries, pagemap):
    heading = doc.add_heading(level=1)
    heading.paragraph_format.first_line_indent = Mm(0)
    # Разрыв ставится перед оглавлением, а не после предыдущего листа:
    # отдельный служебный параграф с разрывом при плотно набранной странице
    # сам не помещается и уезжает на следующую, давая пустой лист.
    heading.paragraph_format.page_break_before = True
    set_font(heading.add_run("СОДЕРЖАНИЕ"), size=16, bold=True)

    for level, title in entries:
        para = doc.add_paragraph()
        pf = para.paragraph_format
        pf.first_line_indent = Mm(0)
        pf.space_after = Pt(0)
        pf.line_spacing = 1.5
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        if level == 2:
            pf.left_indent = Mm(8)
        pf.tab_stops.add_tab_stop(Cm(TEXT_WIDTH_CM), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        set_font(para.add_run(title), size=13, bold=(level == 1))
        page = pagemap.get(title, "") if pagemap else ""
        set_font(para.add_run("\t" + str(page)), size=13)
    doc.add_page_break()


def doc_dir(cfg):
    """Каждый документ лежит в собственной папке: .md, .docx и .pdf вместе."""
    path = os.path.join(BASE_DIR, cfg["file"])
    os.makedirs(path, exist_ok=True)
    return path


def doc_path(cfg, ext):
    return os.path.join(doc_dir(cfg), cfg["file"] + ext)



def change_log(doc, cfg):
    """Лист регистрации изменений: обязательная часть эксплуатационного документа."""
    doc.add_page_break()
    heading = doc.add_heading(level=1)
    heading.paragraph_format.first_line_indent = Mm(0)
    set_font(heading.add_run("ЛИСТ РЕГИСТРАЦИИ ИЗМЕНЕНИЙ"), size=16, bold=True)

    para = doc.add_paragraph()
    add_inline(para, "В таблице фиксируются изменения документа. Версия повышается "
                     "при выпуске новой редакции: вторая цифра при уточнениях и "
                     "дополнениях, первая при переработке структуры или существенном "
                     "изменении требований.")

    headers = ["Версия", "Дата", "Содержание изменения", "Внёс"]
    rows = [[ver, date, text, ""] for ver, date, text in changelog(cfg)]
    rows += [["", "", "", ""] for _ in range(6)]
    add_caption(doc, "Таблица - Регистрация изменений")
    add_table(doc, headers, rows)


def doc_properties(doc, cfg):
    """Свойства файла: их видно в проводнике и в свойствах документа.

    python-docx оставляет в шаблоне свои: автор «python-docx», описание
    «generated by python-docx» и дату создания 2013 года. Получатель открывает
    свойства файла и читает их как выходные данные документа, поэтому здесь они
    заполняются правообладателем и названием документа.
    """
    props = doc.core_properties
    props.title = cfg["title"]
    props.subject = SYSTEM
    props.author = HOLDER
    props.last_modified_by = HOLDER
    props.category = "Эксплуатационная документация"
    props.comments = ""
    props.keywords = ""
    stamp = datetime.datetime.now().replace(microsecond=0)
    props.created = stamp
    props.modified = stamp
    props.revision = 1


def build(cfg, pagemap=None, splitmap=None):
    src = doc_path(cfg, ".md")
    with open(src, encoding="utf-8") as fh:
        blocks = parse_markdown(fh.read())

    probe = Document()
    page_setup(probe.sections[0])
    init_styles(probe)
    toc_titles = []
    render(probe, blocks, toc_titles)

    doc = Document()
    doc_properties(doc, cfg)
    page_setup(doc.sections[0])
    init_styles(doc)
    header_footer(doc)
    cover(doc, cfg)
    render_toc(doc, toc_titles, pagemap)
    tables_meta = []
    render(doc, blocks, [], splitmap, tables_meta)
    if WITH_CHANGELOG:
        change_log(doc, cfg)
    doc.save(doc_path(cfg, ".docx"))
    return toc_titles, tables_meta


def to_pdf(cfg):
    docx = doc_path(cfg, ".docx")
    pdf = doc_path(cfg, ".pdf")
    result = subprocess.run(
        ["soffice", "--headless", "--convert-to", "pdf", "--outdir", doc_dir(cfg), docx],
        capture_output=True, text=True, timeout=300,
    )
    if not os.path.exists(pdf):
        raise RuntimeError(f"конвертация в PDF не удалась: {result.stdout} {result.stderr}")
    return pdf


def pagemap_from_pdf(cfg, entries):
    pdf = doc_path(cfg, ".pdf")
    text = subprocess.run(
        ["pdftotext", "-layout", pdf, "-"], capture_output=True, text=True, check=True
    ).stdout
    pages = text.split("\f")

    # Оглавление занимает несколько страниц и содержит те же заголовки. Строки с
    # точечным лидером отбрасываем, иначе раздел получит номер страницы оглавления.
    def body_only(page):
        return re.sub(r"\s+", " ", " ".join(
            ln for ln in page.splitlines() if "...." not in ln))

    start = 0
    for idx, page in enumerate(pages):
        if "СОДЕРЖАНИЕ" in page:
            start = idx + 1
            break

    pagemap = {}
    for _, title in entries:
        needle = re.sub(r"\s+", " ", title).strip()
        for idx in range(start, len(pages)):
            if needle in body_only(pages[idx]):
                pagemap[title] = idx + 1
                break
    return pagemap




def report_silent_breaks(cfg, quiet=False):
    """Предупредить о таблицах, которые страница рвёт без подписи продолжения.

    Итоговая проверка результата: подбор разбиения опирается на распознавание
    таблиц в текстовом слое PDF и в редком случае может таблицу пропустить.
    """
    with open(doc_path(cfg, ".md"), encoding="utf-8") as fh:
        lines = fh.read().split("\n")

    heads = set()
    for i, line in enumerate(lines):
        if line.strip().startswith("|") and i + 1 < len(lines) and re.match(
            r"^\|[\s:|-]+\|$", lines[i + 1].strip()
        ):
            cells = [re.sub(r"[`*]", "", c).strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 2 and cells[0]:
                heads.add(re.sub(r"\s+", " ", " ".join(cells)))

    pages = subprocess.run(
        ["pdftotext", "-layout", doc_path(cfg, ".pdf"), "-"],
        capture_output=True, text=True, check=True,
    ).stdout.split("\f")

    silent, hanging, hanging_tables = [], [], []
    for number, page in enumerate(pages, 1):
        rows = [ln for ln in page.splitlines() if ln.strip()]
        if not rows:
            continue
        # Подпись продолжения, оказавшаяся не в начале страницы: разрыв, ради
        # которого таблицу разрезали, после пересборки исчез, и подпись висит
        # посреди сплошной таблицы. Подбор проверяет это на своей вёрстке, но
        # финальная сборка добавляет в оглавление номера страниц и способна
        # сдвинуть строку - поэтому проверяем ещё раз по готовому документу.
        for idx, line in enumerate(rows):
            if "Продолжение таблицы" in line and idx != 0:
                hanging.append(number)
                found = re.search(r"Продолжение таблицы ([\w.]+)", line)
                if found:
                    hanging_tables.append(found.group(1))
        if "Продолжение таблицы" in rows[0]:
            continue
        if re.sub(r"\s+", " ", rows[0]).strip() in heads:
            silent.append(number)
    if silent and not quiet:
        print(f"  ВНИМАНИЕ: таблица разорвана без подписи продолжения, страницы: {silent}")
    if hanging and not quiet:
        print(f"  ВНИМАНИЕ: подпись продолжения не в начале страницы: {hanging}")
    return silent, hanging_tables


def build_one(key):
    cfg = DOCS[key]
    name = cfg["file"]

    # Таблицы, которые страница разрывает, обрабатываются по одной сверху вниз:
    # фиксируем разбиение верхней, пересобираем, ищем следующую. Так каждое
    # разбиение определяется на вёрстке, где всё вышележащее уже окончательно.
    splitmap, handled = {}, set()
    entries, tables_meta = build(cfg, None, splitmap)
    to_pdf(cfg)

    for _ in range(60):
        number, breaks = find_first_unsplit_break(cfg, tables_meta, handled)
        if not number:
            break
        handled.add(number)

        # Оценка по текстовому слою приблизительная, поэтому от неё идём шагами
        # в сторону, которую подсказывает вёрстка: подпись повисла на странице
        # начала таблицы - режем ниже, уехала вглубь следующей - выше. Так
        # таблица параметров загрузки доходит от седьмой строки до девятой, где
        # страница её и рвёт; фиксированный набор сдвигов туда не дотягивался.
        placed, point, tried = False, breaks[0], set()
        for _ in range(10):
            if point < 1 or point >= rows_in_table(tables_meta, number) or point in tried:
                dbg(f"таблица {number}: точка {point} вне поиска, остановка")
                break
            tried.add(point)
            splitmap[number] = [point]
            entries, tables_meta = build(cfg, None, splitmap)
            to_pdf(cfg)
            verdict = split_verdict(cfg, number)
            dbg(f"таблица {number}: точка {point} -> {verdict}")
            if verdict == "ok":
                placed = True
                break
            if verdict == "none":
                break
            point += 1 if verdict == "early" else -1
        if not placed:
            dbg(f"таблица {number}: место не найдено, откат")
            splitmap.pop(number, None)
            entries, tables_meta = build(cfg, None, splitmap)
            to_pdf(cfg)

    if splitmap:
        print(f"  таблицы с продолжением: {', '.join(sorted(splitmap))}")

    pagemap = pagemap_from_pdf(cfg, entries)
    missing = [t for _, t in entries if t not in pagemap]
    if missing:
        print(f"  ВНИМАНИЕ: не найдено в PDF {len(missing)}: {missing[:3]}")

    print(f"[{name}] финальная сборка...")
    _, tables_meta = build(cfg, pagemap, splitmap)
    pdf = to_pdf(cfg)

    # Подбор работал на вёрстке без номеров страниц в оглавлении, а финальная
    # сборка их добавляет и сдвигает содержимое: таблица, помещавшаяся при
    # подборе, разъезжается уже в готовом документе. Раньше об этом только
    # печаталось предупреждение, и подпись продолжения так и не появлялась.
    # Разрез одной таблицы сдвигает лежащие ниже, поэтому проходов несколько:
    # закрытый разрыв способен повесить подпись у следующей таблицы.
    for _ in range(6):
        silent, hanging = report_silent_breaks(cfg, quiet=True)
        if not silent and not hanging:
            break
        # Снимок разбиения: правка одной таблицы сдвигает лежащие ниже, и
        # попытка может оставить документ хуже, чем был. Тогда откатываемся.
        before = {k: list(v) for k, v in splitmap.items()}
        trouble = len(silent) + len(hanging)
        number, breaks, known = None, None, []
        if silent:
            # Уже разрезанные пропускаем: их разрыв - тот самый, ради которого
            # разрез и сделан, и без этого поиск возвращает первую из них по кругу.
            number, breaks = find_first_unsplit_break(cfg, tables_meta, set(splitmap))
            if not number:
                # Разрыв в таблице, которая уже разрезана: рвётся её продолжение.
                number = next((n for n in splitmap
                               if next_break_in_tail(cfg, tables_meta, n, splitmap[n])), None)
                if number:
                    known = list(splitmap[number])
                    breaks = [next_break_in_tail(cfg, tables_meta, number, known)]
        if not number and hanging:
            # Подпись повисла посреди сплошной таблицы: точку разреза надо
            # передвинуть, а не искать новый разрыв.
            number = hanging[0]
            known = list(splitmap.get(number, []))[:-1]
            last = splitmap.get(number)
            breaks = [last[-1]] if last else None
        if not number or not breaks or breaks[0] is None:
            break
        point, placed = breaks[0], False
        for _ in range(6):
            if point < 1 or point >= rows_in_table(tables_meta, number):
                break
            splitmap[number] = sorted(set(known + [point]))
            _, tables_meta = build(cfg, pagemap, splitmap)
            to_pdf(cfg)
            verdict = split_verdict(cfg, number, tail=bool(known))
            dbg(f"таблица {number} (после финальной): точка {point} -> {verdict}")
            if verdict == "ok":
                placed = True
                break
            if verdict == "none":
                break
            point += 1 if verdict == "early" else -1
        if not placed:
            splitmap.clear()
            splitmap.update(before)
            _, tables_meta = build(cfg, pagemap, splitmap)
            to_pdf(cfg)
            break
        after_silent, after_hanging = report_silent_breaks(cfg, quiet=True)
        if len(after_silent) + len(after_hanging) >= trouble:
            dbg(f"таблица {number}: правка не улучшила вёрстку, откат")
            splitmap.clear()
            splitmap.update(before)
            _, tables_meta = build(cfg, pagemap, splitmap)
            to_pdf(cfg)
            break

    report_silent_breaks(cfg)
    pages = subprocess.run(["pdfinfo", pdf], capture_output=True, text=True).stdout
    total = re.search(r"Pages:\s+(\d+)", pages)
    print(f"[{cfg['file']}] готово, страниц: {total.group(1) if total else '?'}")


def main():
    check_changelogs()
